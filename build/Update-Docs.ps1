<#
    Regenerates docs/reference/ (one markdown page per exported command) from the module's
    comment-based help via platyPS.

    SINGLE SOURCE OF TRUTH: command facts live in the comment-based help only — this script projects
    them into docs/reference/, and CI fails a PR whose regenerated reference differs from the committed
    one (see .github/workflows/docs.yml). Never hand-edit docs/reference/*.md.

    Pinned to classic platyPS 0.14.x — verified against this module. (The newer
    Microsoft.PowerShell.PlatyPS 1.x generator uses a different schema; upgrade deliberately, not by
    accident.)

    NOTE: importing the module must stay PROMPT-FREE (BasePath prompting happens at command run time,
    not import) — if an import-time prompt ever appears, this script and the CI job will hang.

    Run:  pwsh -File build\Update-Docs.ps1
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
$repo    = Split-Path -Parent $PSScriptRoot
$outDir  = Join-Path $repo 'docs\reference'

# platyPS classic, pinned major.minor.
$platy = Get-Module -ListAvailable -Name platyPS | Where-Object { $_.Version -lt [version]'1.0' } | Sort-Object Version -Descending | Select-Object -First 1
if (-not $platy) {
    Write-Host 'Installing platyPS 0.14.2 (CurrentUser)...' -ForegroundColor Yellow
    Install-Module platyPS -RequiredVersion 0.14.2 -Scope CurrentUser -Force
    $platy = Get-Module -ListAvailable -Name platyPS | Where-Object { $_.Version -lt [version]'1.0' } | Sort-Object Version -Descending | Select-Object -First 1
}
Import-Module $platy -Force

Import-Module (Join-Path $repo 'win32-toolkit.psd1') -Force

if (Test-Path -LiteralPath $outDir) { Remove-Item -LiteralPath $outDir -Recurse -Force }
New-Item -ItemType Directory -Path $outDir -Force | Out-Null

# -NoMetadata: no YAML front matter — the pages must render cleanly on plain GitHub AND on the Zensical site.
$null = New-MarkdownHelp -Module 'win32-toolkit' -OutputFolder $outDir -NoMetadata -Force

# Index page linking every command, in the groups of the mkdocs.yml nav and the README's command tables.
$groups = [ordered]@{
    'Start and package'               = @('Show-Win32Toolkit', 'Invoke-Win32Toolkit', 'New-Win32ToolkitManualApp', 'Complete-Win32ToolkitManualApp')
    'Test'                            = @('Test-Win32ToolkitProject')
    'Build and publish'               = @('Export-Win32ToolkitIntuneWin', 'Publish-Win32ToolkitIntuneApp', 'Export-Win32ToolkitDocumentation')
    'Intune sign-in'                  = @('Connect-Win32ToolkitIntune', 'Disconnect-Win32ToolkitIntune')
    'Dependencies and prior installs' = @('Set-Win32ToolkitAppDependency', 'Sync-Win32ToolkitAppDependency', 'Set-Win32ToolkitPriorInstall')
    'Hyper-V test VM'                 = @('New-Win32ToolkitTestVM', 'Set-Win32ToolkitTestVMResource', 'Reset-Win32ToolkitTestVM', 'Remove-Win32ToolkitTestVM')
}
# Every exported command must be in a group (Connect/Disconnect were once missing from the index).
$exported = @((Get-Module -Name 'win32-toolkit').ExportedFunctions.Keys)
$grouped  = @($groups.Values | ForEach-Object { $_ })
$missing  = @($exported | Where-Object { $_ -notin $grouped })
if ($missing.Count) { throw "Update-Docs: exported command(s) missing from the index groups: $($missing -join ', ')" }
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('# Commands')
[void]$sb.AppendLine()
# No relative link to build\ here: it sits OUTSIDE docs_dir, and `zensical build --strict` fails the
# whole Pages build on links it cannot resolve among the documentation files.
[void]$sb.AppendLine('<!-- Generated by build/Update-Docs.ps1 from the comment-based help in Public/. Do not edit by hand. -->')
[void]$sb.AppendLine()
[void]$sb.AppendLine('This section has one page for each win32-toolkit command. Use these pages when you need every option of a command. The guide explains each task step by step.')
[void]$sb.AppendLine()
[void]$sb.AppendLine('Each page comes from the help that is built into the command. You can read the same text offline: run `Get-Help <command> -Full` in PowerShell.')
[void]$sb.AppendLine()
foreach ($g in $groups.Keys) {
    [void]$sb.AppendLine("## $g")
    [void]$sb.AppendLine()
    foreach ($cmd in $groups[$g]) {
        $syn = (Get-Help $cmd).Synopsis.Trim()
        # Colon, not an em-dash: the docs deliberately avoid em-dashes.
        [void]$sb.AppendLine("- [$cmd]($cmd.md): $syn")
    }
    [void]$sb.AppendLine()
}
[System.IO.File]::WriteAllText((Join-Path $outDir 'README.md'), $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))

# Normalize EVERY generated page (incl. the index just written — StringBuilder.AppendLine emits
# platform CRLF) to LF + UTF-8 (no BOM). The CI drift job compares BYTES across machines: without
# this, a regeneration elsewhere is flagged as drift by line endings alone (an invisible diff).
# Paired with the .gitattributes rule 'docs/reference/*.md text eol=lf'. MUST stay the LAST step.
foreach ($f in Get-ChildItem -LiteralPath $outDir -Filter '*.md') {
    $text = [System.IO.File]::ReadAllText($f.FullName)
    $text = $text.Replace("`r`n", "`n")
    # platyPS 0.14 lists PowerShell 7.4's -ProgressAction common parameter as a normal parameter with a
    # '{{ Fill ProgressAction Description }}' placeholder. It is a common parameter: drop it from the
    # syntax blocks and its section (CommonParameters already covers it).
    $text = [regex]::Replace($text, ' ?\[-ProgressAction <ActionPreference>\]', '')
    $text = [regex]::Replace($text, '(?s)### -ProgressAction\n.*?\n(?=### |## )', '')
    # platyPS copies Get-Help's 'Default value', which is wrong in three cases. A typed parameter with no
    # default in param() shows the zero of its type ('0', though the help says 'Default: 300' or the range
    # starts at 1). A default computed by a command shows the call (a private function name). Both become
    # 'None', as for every other parameter without a default; the help text above says the real default
    # in words. A plain string default gets its first letter upper-cased ('Win32tk-golden', 'AutoInstall'):
    # it is written exactly as in param(). Switches keep 'False'. The command's own Public\<Command>.ps1 is
    # the source.
    $cmdName = $f.BaseName
    $src = Join-Path $repo "Public\$cmdName.ps1"
    if (Test-Path -LiteralPath $src) {
        $ast = [System.Management.Automation.Language.Parser]::ParseFile($src, [ref]$null, [ref]$null)
        $fn  = $ast.Find({ param($a) $a -is [System.Management.Automation.Language.FunctionDefinitionAst] -and $a.Name -eq $cmdName }, $true)
        if (-not $fn) { throw "Update-Docs: function $cmdName not found in $src." }
        foreach ($p in @($fn.Body.ParamBlock.Parameters)) {
            if ($p.StaticType -eq [switch]) { continue }
            $byCommand = $p.DefaultValue -and $p.DefaultValue.Find({ param($a) $a -is [System.Management.Automation.Language.CommandAst] }, $true)
            if (-not $p.DefaultValue -or $byCommand) { $value = 'None' }
            elseif ($p.DefaultValue -is [System.Management.Automation.Language.StringConstantExpressionAst]) { $value = $p.DefaultValue.Value.Trim() }
            else { continue }
            $pName = $p.Name.VariablePath.UserPath
            $rx    = "(?s)(### -$([regex]::Escape($pName))\n(?:(?!\n### ).)*?\nDefault value: )[^\n]*"
            if (-not [regex]::IsMatch($text, $rx)) { throw "Update-Docs: no 'Default value' line for -$pName in $($f.Name)." }
            $text = [regex]::Replace($text, $rx, { param($m) $m.Groups[1].Value + $value })
        }
    }
    [System.IO.File]::WriteAllText($f.FullName, $text, (New-Object System.Text.UTF8Encoding($false)))
}

$count = @(Get-ChildItem -LiteralPath $outDir -Filter '*.md').Count
Write-Host "✓ docs/reference regenerated: $count page(s)." -ForegroundColor Green
