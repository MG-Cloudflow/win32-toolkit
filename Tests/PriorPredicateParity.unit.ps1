<#
    Installer-identity PR 3 (S13, D28, V2, V13, spec 2.9): ONE prior-install predicate, several consumers, the same
    answer. For every row of a shared fixture table (Notepad++ x64 / ARM64 / x86 names, padded versions '8.9' / '8.9.0',
    '26.02' / '26.2', '4.4' / '4.4.0', VLC '3.0.17.4' in a '3.0.17' window, Python '3.12.10150.0', .NET '8.0.32.36605',
    unreadable versions ('x.y', a 10-digit part, '8.9.1234567890', '8.9.8.1.5'), WindowsInstaller 1, publisher drift, a
    {v} template match / mismatch, below / at VersionMin / inside / at VersionMax / above the window, the other registry
    view, an absent key):
      (a) the update requirement script generated by the REAL generator from a fixture project whose ONLY signal is the
          fifth (no tattoo, no UpgradeCode, no product codes, no names - asserted) -> exit 0 + '1' exactly when Proven;
      (b) the deploy script's PriorEvaluate (the entry as Report, so no file system is needed) -> its State;
      (c) the predicate itself ($w32tPrState) -> its State;
    are run in Windows PowerShell 5.1 children with every registry call shadowed, and must agree row by row with the
    expected state. (The Update test's guest assertions join this table with installer-identity PR 3 U1.)

    Nothing is installed; projects under %TEMP%. Run:  pwsh -File Tests\PriorPredicateParity.unit.ps1
#>
[Diagnostics.CodeAnalysis.SuppressMessageAttribute('PSUseShouldProcessForStateChangingFunctions', '', Justification = 'test fixture builders')]
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent $PSScriptRoot
$fail = 0
function Ok($m)  { Write-Host "  PASS: $m" -ForegroundColor Green }
function Bad($m) { Write-Host "  FAIL: $m" -ForegroundColor Red; $script:fail++ }

foreach ($f in 'Get-Win32ToolkitAppConfig', 'ConvertTo-PSSingleQuoted', 'Test-Win32ToolkitProductCode', 'Get-Win32ToolkitRequirementRule', 'Test-Win32ToolkitPriorInstallEntry',
    'ConvertTo-Win32ToolkitPriorVersion', 'Get-Win32ToolkitDeployScriptBlock', 'Get-Win32ToolkitDeployScriptShape', 'Test-Win32ToolkitPsadtVersionSupported', 'ConvertTo-Win32ToolkitSafeText') {
    . (Join-Path $repo "Private\$f.ps1")
}
$script:PsadtSupportedRange = [pscustomobject]@{ Min = [version]'4.1.0'; MaxExclusive = [version]'4.3.0'; Display = '4.1.x and 4.2.x' }
function Get-Win32ToolkitMsiProperty { param([string]$Path, [string]$Property) $null = $Path, $Property; '' }

$ps51 = Join-Path $env:windir 'System32\WindowsPowerShell\v1.0\powershell.exe'
if (-not (Test-Path -LiteralPath $ps51)) { Write-Host 'SKIP: Windows PowerShell 5.1 not present' -ForegroundColor DarkYellow; exit 3 }

$root = Join-Path ([IO.Path]::GetTempPath()) ('w32par_' + [guid]::NewGuid().ToString('N').Substring(0, 8))
$null = New-Item -ItemType Directory -Path $root -Force
$utf8 = [Text.UTF8Encoding]::new($false)
$PC = '{5C6F8543-7EA8-40B9-B78F-04C78300DE7F}'

# Entry window and identity per row; Observed = what the device registry holds (View, Key, values); Want = the state.
function Row([string]$L, [string]$Want, [hashtable]$E = @{}, [hashtable]$O = @{}, [string]$ObsView = 'Native', [string]$ObsKey = 'Notepad++', [switch]$Absent) {
    $entry = [ordered]@{ Id = 'p'; Kind = 'ArpKey'; Mode = 'Enforce'; Key = 'Notepad++'; View = 'Native'; Publisher = 'Notepad++ Team'; DisplayName = 'Notepad++ (64-bit x64)'; DisplayNameTemplate = ''
        VersionMin = '8.8.9'; VersionMax = '8.9.8.1'; UninstallerType = 'nullsoft'; UninstallerFileName = 'uninstall.exe'; UninstallerSigner = ''; InstallDir = '%ProgramFiles%\Notepad++'
        MainExe = 'notepad++.exe'; ProcessNames = @('notepad++'); Source = 'Operator'; Track = 'Current'; AddedOn = '2026-10-25' }
    foreach ($k in $E.Keys) { $entry[$k] = $E[$k] }
    $obs = [ordered]@{ DisplayName = 'Notepad++ (64-bit x64)'; DisplayVersion = '8.9.5'; Publisher = 'Notepad++ Team'; UninstallString = '"C:\Program Files\Notepad++\uninstall.exe"' }
    foreach ($k in $O.Keys) { $obs[$k] = $O[$k] }
    [pscustomobject]@{ L = $L; Want = $Want; Entry = $entry; Obs = $obs; ObsView = $ObsView; ObsKey = $ObsKey; Absent = [bool]$Absent }
}
$rows = @(
    (Row 'Notepad++ x64 inside the window' 'Proven')
    (Row 'Notepad++ ARM64 name' 'Unverified' -O @{ DisplayName = 'Notepad++ (ARM64)' })
    (Row 'Notepad++ x86 name' 'Unverified' -O @{ DisplayName = 'Notepad++ (32-bit x86)' })
    (Row "'8.9' observed, '8.9.0' VersionMax" 'Proven' -E @{ VersionMin = '8.0'; VersionMax = '8.9.0' } -O @{ DisplayVersion = '8.9' })
    (Row "'26.02' observed in a '26.2' window" 'Proven' -E @{ VersionMin = '26.2'; VersionMax = '26.2' } -O @{ DisplayVersion = '26.02' })
    (Row "'4.4' observed, '4.4.0' window" 'Proven' -E @{ VersionMin = '4.4.0'; VersionMax = '4.4.0' } -O @{ DisplayVersion = '4.4' })
    (Row "'x.y' unreadable" 'Unverified' -O @{ DisplayVersion = 'x.y' })
    (Row "VLC '3.0.17.4' above a '3.0.17' max" 'Newer' -E @{ VersionMin = '3.0.0'; VersionMax = '3.0.17' } -O @{ DisplayVersion = '3.0.17.4' })
    (Row "Python '3.12.10150.0' in its window" 'Proven' -E @{ VersionMin = '3.12.0'; VersionMax = '3.12.10150.0' } -O @{ DisplayVersion = '3.12.10150.0' })
    (Row ".NET '8.0.32.36605' in its window" 'Proven' -E @{ VersionMin = '8.0'; VersionMax = '8.0.32.36605' } -O @{ DisplayVersion = '8.0.32.36605' })
    (Row 'a 10-digit part' 'Unverified' -O @{ DisplayVersion = '1234567890' })
    (Row "'8.9.1234567890' (unreadable)" 'Unverified' -O @{ DisplayVersion = '8.9.1234567890' })
    (Row "'8.9.8.1.5' (unreadable)" 'Unverified' -O @{ DisplayVersion = '8.9.8.1.5' })
    (Row 'WindowsInstaller 1' 'Unverified' -O @{ WindowsInstaller = 1 })
    (Row 'publisher drift' 'Unverified' -O @{ Publisher = 'Don Ho' })
    (Row 'publisher case differs (ordinal ignore case)' 'Proven' -O @{ Publisher = 'NOTEPAD++ TEAM' })
    (Row 'template match' 'Proven' -E @{ DisplayName = ''; DisplayNameTemplate = 'Notepad++ {v} (64-bit)' } -O @{ DisplayName = 'Notepad++ 8.9.5 (64-bit)' })
    (Row 'template mismatch' 'Unverified' -E @{ DisplayName = ''; DisplayNameTemplate = 'Notepad++ {v} (64-bit)' } -O @{ DisplayName = 'Notepad++ 8.9.4 (64-bit)' })
    (Row 'below VersionMin' 'Unverified' -O @{ DisplayVersion = '8.8.8' })
    (Row 'at VersionMin' 'Proven' -O @{ DisplayVersion = '8.8.9' })
    (Row "NSIS '8.8.9' inside an '8.8.9 ... 8.9.8.1' window" 'Proven' -O @{ DisplayVersion = '8.8.9' })
    (Row 'at VersionMax' 'Proven' -O @{ DisplayVersion = '8.9.8.1' })
    (Row 'above VersionMax' 'Newer' -O @{ DisplayVersion = '8.9.9' })
    (Row 'no VersionMin: any older version' 'Proven' -E @{ VersionMin = '' } -O @{ DisplayVersion = '1.0' })
    (Row 'the key only in the other view' 'Absent' -ObsView 'Wow6432')
    (Row 'the Wow6432 entry, key in WOW6432Node' 'Proven' -E @{ View = 'Wow6432' } -ObsView 'Wow6432')
    (Row 'the key is absent' 'Absent' -Absent)
)

# One requirement script per row, from the REAL generator.
$blocks = "## win32-toolkit:Pre-Install:prior-check (begin) - x`r`n## remove-prior catalog revision $(Get-Win32ToolkitDeployScriptBlock -Name RemovePriorRevision) (win32-toolkit)`r`n## win32-toolkit:Pre-Install:prior-check (end)`r`n## win32-toolkit:Pre-Install:remove-prior (begin) - x`r`n## win32-toolkit:Pre-Install:remove-prior (end)`r`n"
$cases = [System.Collections.Generic.List[object]]::new()
$i = 0
try {
    foreach ($r in $rows) {
        $i++
        $p = Join-Path $root "p$i"
        $null = New-Item -ItemType Directory -Path (Join-Path $p 'SupportFiles'), (Join-Path $p 'Files') -Force
        $cfg = [ordered]@{ App = [ordered]@{ Vendor = ''; Name = ''; DisplayName = ''; Version = '9.0'; ScriptAuthor = 'Contoso IT' }; Installer = [ordered]@{ Type = 'msi'; FileName = 'x.msi' }
            OwnIdentity = [ordered]@{ ProductCode = $PC; ArpKeys = @([ordered]@{ Key = $PC; View = 'Native' }) }; PriorInstalls = [ordered]@{ SchemaVersion = '1.0'; Entries = @($r.Entry) } }
        [IO.File]::WriteAllText((Join-Path $p 'SupportFiles\AppConfig.json'), ($cfg | ConvertTo-Json -Depth 8), $utf8)
        [IO.File]::WriteAllText((Join-Path $p 'Invoke-AppDeployToolkit.ps1'), $blocks, [Text.UTF8Encoding]::new($true))
        $rule = Get-Win32ToolkitRequirementRule -ProjectPath $p 3>$null
        $script = [Text.Encoding]::UTF8.GetString([Convert]::FromBase64String($rule['scriptContent'])).TrimStart([char]0xFEFF)
        if ($i -eq 1) {
            # The fixture's ONLY signal is the fifth: exit 0 can only come from it.
            $ast = [Management.Automation.Language.Parser]::ParseInput($script, [ref]$null, [ref]$null)
            $other = @($ast.FindAll({ param($n) $n -is [Management.Automation.Language.CommandAst] -and $n.GetCommandName() -eq 'Test-Path' -and $n.Extent.Text -notmatch '\$w32t' }, $true))
            if ($script.Contains('$w32tPrData') -and -not $script.Contains('RelatedProducts') -and -not $script.Contains('$targets') -and $other.Count -eq 0) { Ok 'the generated requirement has no other signal than the fifth (no tattoo, UpgradeCode, product code or name probe)' } else { Bad "other signals in the fixture requirement:`n$script" }
        }
        $sp = Join-Path $root "req$i.ps1"
        [IO.File]::WriteAllText($sp, $script, [Text.UTF8Encoding]::new($true))
        $cases.Add([ordered]@{ L = $r.L; Want = $r.Want; Req = $sp; Entry = $r.Entry; Obs = $r.Obs; ObsView = $r.ObsView; ObsKey = $r.ObsKey; Absent = $r.Absent })
    }
    $casesFile = Join-Path $root 'cases.json'
    [IO.File]::WriteAllText($casesFile, ($cases | ConvertTo-Json -Depth 6), $utf8)
    $predFile = Join-Path $root 'predicate.ps1'; $evalFile = Join-Path $root 'evaluate.ps1'
    [IO.File]::WriteAllText($predFile, (Get-Win32ToolkitDeployScriptBlock -Name PriorPredicate), [Text.UTF8Encoding]::new($true))
    [IO.File]::WriteAllText($evalFile, (Get-Win32ToolkitDeployScriptBlock -Name PriorEvaluate), [Text.UTF8Encoding]::new($true))

    $harness = @'
param([string]$CasesFile, [string]$PredFile, [string]$EvalFile)
Set-StrictMode -Version 1
$ErrorActionPreference = 'Stop'
$cases = Get-Content -LiteralPath $CasesFile -Raw -Encoding UTF8 | ConvertFrom-Json
# Global: the requirement script runs as its own script file, where $script: would name ITS scope.
$global:W32tParityReg = @{}
$arp = @{ Native = 'HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall'; Wow6432 = 'HKLM:\SOFTWARE\WOW6432Node\Microsoft\Windows\CurrentVersion\Uninstall' }
function Test-Path {
    [CmdletBinding()] param([string]$LiteralPath, [string]$Path, [string]$PathType)
    $p = $LiteralPath; if (-not $p) { $p = $Path }
    if ($p -notlike 'HKLM:\SOFTWARE\*Microsoft\Windows\CurrentVersion\Uninstall\*') { throw "unexpected path $p" }
    return $global:W32tParityReg.ContainsKey($p.ToLowerInvariant())
}
function Get-ItemProperty {
    [CmdletBinding()] param([string]$LiteralPath, [string]$Path, [string]$Name)
    $p = $LiteralPath; if (-not $p) { $p = $Path }
    $k = $global:W32tParityReg[$p.ToLowerInvariant()]
    if ($null -eq $k) { throw "no key $p" }
    $o = New-Object psobject
    foreach ($n in @($k.Keys)) { $o | Add-Member -MemberType NoteProperty -Name $n -Value $k[$n] }
    $o
}
$predText = [IO.File]::ReadAllText($PredFile); $evalText = [IO.File]::ReadAllText($EvalFile)
. ([scriptblock]::Create($predText))
. ([scriptblock]::Create($evalText))
$cfg = New-Object psobject -Property @{ App = (New-Object psobject -Property @{ Version = '9.0' }); Installer = (New-Object psobject -Property @{ Type = 'msi' })
    OwnIdentity = (New-Object psobject -Property @{ ProductCode = '{5C6F8543-7EA8-40B9-B78F-04C78300DE7F}'; ArpKeys = @() }) }
foreach ($c in @($cases)) {
    $global:W32tParityReg = @{}
    if (-not $c.Absent) {
        $vals = @{}
        foreach ($pp in $c.Obs.PSObject.Properties) { $vals[$pp.Name] = $pp.Value }
        $global:W32tParityReg[("$($arp[$c.ObsView])\$($c.ObsKey)").ToLowerInvariant()] = $vals
    }
    # (a) the requirement script
    $out = @(& $c.Req)
    $req = if ($LASTEXITCODE -eq 0 -and ($out -join '') -eq '1') { 'met' } else { 'not met' }
    # (c) the predicate
    $state = (& $w32tPrState $c.Entry).State
    # (b) the deploy script's evaluation, the entry as Report (no file system involved)
    $rep = $c.Entry.PSObject.Copy(); $rep.Mode = 'Report'
    $ev = & $w32tPrEvaluate $rep $cfg
    $evState = switch ($ev.Outcome) { 'Report' { [string]$ev.State } 'Unproven' { 'Unverified' } 'Absent' { 'Absent' } default { 'Outcome ' + $ev.Outcome } }
    'ROW|' + $c.L + '|' + $c.Want + '|' + $req + '|' + $state + '|' + $evState
}
'@
    $hFile = Join-Path $root 'harness.ps1'
    [IO.File]::WriteAllText($hFile, $harness, [Text.UTF8Encoding]::new($true))
    $out = @(& $ps51 -NoProfile -ExecutionPolicy Bypass -File $hFile -CasesFile $casesFile -PredFile $predFile -EvalFile $evalFile 2>&1 | ForEach-Object { "$_" })
    $seen = 0
    foreach ($l in $out) {
        if ($l -notlike 'ROW|*') { if ($l.Trim()) { Write-Host "  | $l" -ForegroundColor DarkGray }; continue }
        $seen++
        $x = $l.Split('|')
        $label = $x[1]; $want = $x[2]; $req = $x[3]; $state = $x[4]; $ev = $x[5]
        $reqWant = if ($want -eq 'Proven') { 'met' } else { 'not met' }
        if ($state -eq $want -and $ev -eq $want -and $req -eq $reqWant) { Ok "$label -> $want (predicate, deploy evaluation and requirement '$req' agree)" }
        else { Bad "$label : want $want; predicate $state, deploy evaluation $ev, requirement $req" }
    }
    if ($seen -eq $rows.Count) { Ok "all $seen rows ran in Windows PowerShell 5.1" } else { Bad "only $seen of $($rows.Count) rows ran" }
}
finally {
    Remove-Item -LiteralPath $root -Recurse -Force -ErrorAction SilentlyContinue
}

Write-Host ''
if ($fail -eq 0) { Write-Host 'All PriorPredicateParity tests passed.' -ForegroundColor Green; exit 0 }
else { Write-Host "$fail PriorPredicateParity test(s) FAILED." -ForegroundColor Red; exit 1 }
