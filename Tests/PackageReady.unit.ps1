function Get-Win32ToolkitProjectPsadtVersion { param([string]$ProjectPath) $null = $ProjectPath; $script:pv }
function Test-Win32ToolkitPS51Syntax { param([string]$Path) $null = $Path; $script:ps51Calls++; [string[]]@($script:ps51) }

