function Build-PkgProject {
    param([string]$Name, [AllowNull()][string]$Script = $goodScript, [switch]$NoLauncher, [string]$Parent = $root)
    $p = Join-Path $Parent $Name
    New-Item -ItemType Directory -Path $p -Force | Out-Null
    if ($null -ne $Script -and $Script -ne '<none>') {
        [System.IO.File]::WriteAllText((Join-Path $p 'Invoke-AppDeployToolkit.ps1'), $Script, (New-Object System.Text.UTF8Encoding($true)))
    }
    # The launcher only has to EXIST (it is never run): an empty stand-in is enough.
    if (-not $NoLauncher) { [System.IO.File]::WriteAllBytes((Join-Path $p 'Invoke-AppDeployToolkit.exe'), [byte[]]@()) }
    $p
}

# Runs the gate; returns the result, the ErrorRecord (or $null) and the warnings it wrote.
function Invoke-Gate {
    param([string]$ProjectPath, [string]$Stage, [switch]$AllowLegacyScript)
    $res = $null; $err = $null; $w = $null
    try {
        $res = Assert-Win32ToolkitPackageReady -ProjectPath $ProjectPath -Stage $Stage -AllowLegacyScript:$AllowLegacyScript -WarningVariable w 3>$null
    }
    catch { $err = $_ }
    [pscustomobject]@{
        Result   = $res
        Error    = $err
        Warnings = @($w | ForEach-Object { "$_" })
        Lines    = if ($err) { @("$($err.Exception.Message)" -split '\r?\n') } else { @() }
    }
}
function Test-NotReady($r) { $r.Error -and $r.Error.FullyQualifiedErrorId -eq 'W32T.PackageNotReady' }

