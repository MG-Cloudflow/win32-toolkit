    $r = Invoke-Gate -ProjectPath $good -Stage Finalize
    if (-not $r.Error -and $r.Warnings.Count -eq 0 -and $r.Result.VersionText -ceq '4.2.0') { Ok 'Finalize -> Ready, no warning (VersionText still reported)' } else { Bad "Finalize -> error='$($r.Error)' warnings=$($r.Warnings -join ' | ')" }
