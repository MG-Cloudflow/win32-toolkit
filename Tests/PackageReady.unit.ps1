    $r = Invoke-Gate -ProjectPath $good -Stage Export -AllowLegacyScript
    if (-not $r.Error -and @($r.Warnings | Where-Object { $_ -match 'not a supported pair' }).Count -eq 1) { Ok 'Export -AllowLegacyScript -> Ready with the pair warning' } else { Bad "Export -AllowLegacyScript -> error='$($r.Error)' warnings=$($r.Warnings -join ' | ')" }
    Initialize-TestDouble
    Use-ShapeResult -Shape 'Psadt42Default' -Dasv '4.2.0' -Support 'Unsupported' -SupportReason 'Psadt42Default is not supported.'
    Use-ProjectVersionResult -IsSupported $false -Reason 'shape Psadt42Default is not supported'
    $r = Invoke-Gate -ProjectPath $good -Stage Export
    if (@($r.Lines | Where-Object { $_ -match $prefixRx }).Count -eq 1 -and @($r.Lines | Where-Object { $_ -match 'not a supported pair' }).Count -eq 0) { Ok 'an unsupported shape is reported once (no duplicate pair line)' }
    else { Bad "duplicate shape/pair lines: $($r.Lines -join ' | ')" }

    # == [11] every problem in ONE exception ===========================================================
    Write-Host '[11] all errors are collected and thrown once' -ForegroundColor Cyan
    $worst = Build-PkgProject -Name 'Worst' -NoLauncher
    Initialize-TestDouble
    Use-ShapeResult -Shape 'Unknown' -Dasv $null -IsPatched $false -GeneratorVersion $null -HasTattoo $false -Support 'Unsupported' -SupportReason 'Unknown template shape.'
    $script:ps51 = @('Unexpected token ''??''.')
    $r = Invoke-Gate -ProjectPath $worst -Stage Export
    $body = @($r.Lines | Select-Object -Skip 1 | Select-Object -SkipLast 1)
    if ((Test-NotReady $r) -and $body.Count -eq 4) { Ok 'Export: loader + shape + 5.1 + launcher = 4 problem lines in one W32T.PackageNotReady' } else { Bad "Export: $($body.Count) problem line(s): $($r.Lines -join ' | ')" }
    if ($r.Lines[0] -match "^win32-toolkit cannot vouch for the deploy script of '.+Worst' \(stage Export\):$") { Ok 'first line names the project and the stage' } else { Bad "first line: $($r.Lines[0])" }
    if ($r.Lines[-1] -ceq 'Nothing was packaged or published. Fix each problem above and retry.') { Ok 'last line: nothing was packaged or published' } else { Bad "last line: $($r.Lines[-1])" }
    if ($r.Warnings.Count -eq 1 -and $r.Warnings[0] -match 'tattoo') { Ok 'the warning-only finding (no tattoo) is still written as a warning' } else { Bad "warnings: $($r.Warnings -join ' | ')" }
    $r = Invoke-Gate -ProjectPath $worst -Stage Finalize
    $body = @($r.Lines | Select-Object -Skip 1 | Select-Object -SkipLast 1)
    if ((Test-NotReady $r) -and $body.Count -eq 2 -and $r.Lines[-1] -ceq 'Nothing was tested, packaged or published. Fix each problem above and retry.') { Ok 'Finalize: loader + shape = 2 problem lines (no 5.1 / launcher check)' }
    else { Bad "Finalize: $($r.Lines -join ' | ')" }
    $r = Invoke-Gate -ProjectPath $worst -Stage Export -AllowLegacyScript
    $body = @($r.Lines | Select-Object -Skip 1 | Select-Object -SkipLast 1)
    if ((Test-NotReady $r) -and $body.Count -eq 2 -and $r.Warnings.Count -eq 3) { Ok '-AllowLegacyScript: 5.1 + launcher stay errors; loader + shape become warnings (+ tattoo)' }
    else { Bad "-AllowLegacyScript: $($body.Count) error(s), $($r.Warnings.Count) warning(s): $($r.Lines -join ' | ')" }

    # == [12] the ErrorRecord ==========================================================================
    Write-Host '[12] the error record (C-1)' -ForegroundColor Cyan
    $r = Invoke-Gate -ProjectPath $worst -Stage Export
    $e = $r.Error
    if ($e.FullyQualifiedErrorId -ceq 'W32T.PackageNotReady') { Ok 'FullyQualifiedErrorId = W32T.PackageNotReady' } else { Bad "FQID = $($e.FullyQualifiedErrorId)" }
    if ($e.Exception -is [System.InvalidOperationException]) { Ok 'InvalidOperationException' } else { Bad "exception: $($e.Exception.GetType().FullName)" }
    if ($e.CategoryInfo.Category -eq 'InvalidData' -and "$($e.TargetObject)" -eq $worst) { Ok 'category InvalidData, target = the project path' } else { Bad "category '$($e.CategoryInfo.Category)' target '$($e.TargetObject)'" }
    $ascii = @([System.Text.Encoding]::UTF8.GetBytes("$($e.Exception.Message)") | Where-Object { $_ -gt 127 }).Count -eq 0
    if ($ascii) { Ok 'the message is ASCII' } else { Bad 'non-ASCII characters in the message' }

    # == [13] the gate never changes the project =======================================================
    Write-Host '[13] the gate changes nothing (read-only)' -ForegroundColor Cyan
    $before = @(Get-ChildItem -LiteralPath $root -Recurse -File | ForEach-Object { "$($_.FullName)|$($_.Length)|$($_.LastWriteTimeUtc.Ticks)" }) -join "`n"
    Initialize-TestDouble
    $null = Invoke-Gate -ProjectPath $plain -Stage Export
    $null = Invoke-Gate -ProjectPath $legacy -Stage Export -AllowLegacyScript
    $after = @(Get-ChildItem -LiteralPath $root -Recurse -File | ForEach-Object { "$($_.FullName)|$($_.Length)|$($_.LastWriteTimeUtc.Ticks)" }) -join "`n"
    if ($before -ceq $after) { Ok 'no file was created, changed or removed' } else { Bad 'the gate touched the project files' }

    # == [14] contract surface =========================================================================
    Write-Host '[14] contract surface (spec 2.11, C-4)' -ForegroundColor Cyan
    $cmd = Get-Command Assert-Win32ToolkitPackageReady
    $stageSet = @($cmd.Parameters['Stage'].Attributes | Where-Object { $_ -is [System.Management.Automation.ValidateSetAttribute] } | ForEach-Object { $_.ValidValues })
    if (($stageSet -join ',') -eq 'Finalize,Export') { Ok '-Stage is ValidateSet Finalize, Export' } else { Bad "-Stage set: $($stageSet -join ',')" }
    if ($cmd.Parameters['AllowLegacyScript'].SwitchParameter -and $cmd.Parameters['ProjectPath'].Attributes.Where({ $_ -is [System.Management.Automation.ParameterAttribute] }).Mandatory) { Ok '-ProjectPath mandatory, -AllowLegacyScript a switch' } else { Bad 'parameter surface changed' }
    $threw = $false
    try { $null = Assert-Win32ToolkitPackageReady -ProjectPath $good -Stage 'Publish' 3>$null } catch { $threw = $true }
    if ($threw) { Ok 'an unknown stage is rejected' } else { Bad 'stage Publish accepted' }
    $bytes = [System.IO.File]::ReadAllBytes($assertPath)
    if (@($bytes | Where-Object { $_ -gt 127 }).Count -eq 0) { Ok 'Assert-Win32ToolkitPackageReady.ps1 is ASCII-only' } else { Bad 'non-ASCII bytes in the Assert file' }

    # == [15] Export wiring ============================================================================
    Write-Host '[15] Export-Win32ToolkitIntuneWin runs the gate first and lets W32T.* through (C-2)' -ForegroundColor Cyan
    . (Join-Path $repo 'Public\Export-Win32ToolkitIntuneWin.ps1')
    # Export's first helper after the gate (called unconditionally, before IntuneWinAppUtil.exe is located,
    # downloaded or run, before Staging and before any publish): reaching it proves the gate passed, and
    # its sentinel (W32T.*, so C-2 lets it through) stops the run there. Assigned through the function:
    # drive because the shadow must keep the real (plural) name.
    ${function:Get-Win32ToolkitPaths} = {
        param([string]$BasePath)
        $null = $BasePath
        throw [System.Management.Automation.ErrorRecord]::new([System.InvalidOperationException]::new('sentinel'), 'W32T.TestSentinel',
            [System.Management.Automation.ErrorCategory]::OperationStopped, $null)
    }
    function Publish-Win32ToolkitIntuneApp { throw 'Publish-Win32ToolkitIntuneApp must not be reached' }

    $tier = Join-Path $root 'Base\Projects\Contoso'
    New-Item -ItemType Directory -Path $tier -Force | Out-Null
    $expGood   = Build-PkgProject -Name 'ExpGood' -Parent $tier
    $expLegacy = Build-PkgProject -Name 'ExpLegacy' -Parent $tier
    $expBad    = Build-PkgProject -Name 'ExpBad' -Parent $tier

    function Invoke-ExportGate {
        param([string]$ProjectPath, [switch]$AllowLegacyScript)
        $err = $null; $w = $null
        try { Export-Win32ToolkitIntuneWin -ProjectPath $ProjectPath -NoPublishPrompt -AllowLegacyScript:$AllowLegacyScript -WarningVariable w 3>$null 6>$null }
        catch { $err = $_ }
        [pscustomobject]@{ Error = $err; Warnings = @($w | ForEach-Object { "$_" }) }
    }

    Initialize-TestDouble
    $x = Invoke-ExportGate -ProjectPath $expGood
    if ($x.Error.FullyQualifiedErrorId -eq 'W32T.TestSentinel') { Ok 'supported project -> past the gate (sentinel reached)' } else { Bad "supported project -> $($x.Error.FullyQualifiedErrorId): $($x.Error)" }

    Initialize-TestDouble
    Use-ShapeResult -Shape 'Psadt41' -GeneratorVersion 0 -Support 'Legacy' -SupportReason $legacyText
    Use-ProjectVersionResult -IsLegacy $true -Warning $legacyText
    $x = Invoke-ExportGate -ProjectPath $expLegacy
    if ($x.Error.FullyQualifiedErrorId -eq 'W32T.TestSentinel' -and @($x.Warnings | Where-Object { $_ -match 'older win32-toolkit' }).Count -eq 1) { Ok 'legacy project, the TUI call shape (-NoPublishPrompt, no switch) -> past the gate with one legacy warning' }
    else { Bad "legacy project -> $($x.Error.FullyQualifiedErrorId); warnings: $($x.Warnings -join ' | ')" }

    Initialize-TestDouble
    Use-ShapeResult -Shape 'Psadt42Default' -Dasv '4.2.0' -IsPatched $false -GeneratorVersion $null -Support 'Unsupported' -SupportReason 'Psadt42Default is not supported.'
    $x = Invoke-ExportGate -ProjectPath $expBad
    if ($x.Error.FullyQualifiedErrorId -eq 'W32T.PackageNotReady') { Ok 'unsupported project -> W32T.PackageNotReady passes through Export unchanged (C-2)' } else { Bad "unsupported project -> $($x.Error.FullyQualifiedErrorId): $($x.Error)" }
    if ("$($x.Error.Exception.Message)" -notmatch '^Export-Win32ToolkitIntuneWin failed') { Ok 'not re-wrapped as a plain "Export ... failed" string' } else { Bad 're-wrapped by the Export catch' }
    if (@("$($x.Error.Exception.Message)" -split '\r?\n' | Where-Object { $_ -match $prefixRx }).Count -eq 1) { Ok 'the message keeps its "Unsupported PSADT template shape: " line' } else { Bad 'prefix line lost' }
    if (-not (Test-Path -LiteralPath (Join-Path $root 'Base\Staging')) -and -not (Test-Path -LiteralPath (Join-Path $root 'Base\IntuneWin'))) { Ok 'no Staging\ or IntuneWin\ folder was created' } else { Bad 'Export created output before the gate' }

    $x = Invoke-ExportGate -ProjectPath $expBad -AllowLegacyScript
    if ($x.Error.FullyQualifiedErrorId -eq 'W32T.TestSentinel' -and @($x.Warnings | Where-Object { $_ -match $prefixRx }).Count -eq 1) { Ok 'Export -AllowLegacyScript is passed to the gate -> past it with the shape warning' }
    else { Bad "Export -AllowLegacyScript -> $($x.Error.FullyQualifiedErrorId); warnings: $($x.Warnings -join ' | ')" }

    # == [16] C-2 lines in source ======================================================================
    Write-Host '[16] Export and Publish catches start with the C-2 re-throw' -ForegroundColor Cyan
    foreach ($rel in 'Public\Export-Win32ToolkitIntuneWin.ps1', 'Public\Publish-Win32ToolkitIntuneApp.ps1') {
        $ast = [System.Management.Automation.Language.Parser]::ParseFile((Join-Path $repo $rel), [ref]$null, [ref]$null)
        $fn  = $ast.Find({ param($n) $n -is [System.Management.Automation.Language.FunctionDefinitionAst] }, $false)
        $try = @($fn.Body.EndBlock.Statements | Where-Object { $_ -is [System.Management.Automation.Language.TryStatementAst] })
        $first = if ($try.Count) { $try[-1].CatchClauses[0].Body.Statements[0].Extent.Text } else { '' }
        if ($first -ceq "if (`$_.FullyQualifiedErrorId -like 'W32T.*') { throw }") { Ok "$rel" } else { Bad "$rel catch starts with: $first" }
    }

    # == [18] prerelease bundled PSADT (F-05) ==========================================================
    # A prerelease is allowed (testing 4.2 rc side by side) but must be flagged once, at Export only, and
    # must never block packaging.
    Write-Host '[18] a prerelease bundled PSADT warns once at Export and never blocks' -ForegroundColor Cyan
    $pre = Build-PkgProject -Name 'Prerelease'
    Initialize-TestDouble; Use-ProjectVersionResult -VersionText '4.2.0-rc2' -Prerelease 'rc2'
    $r = Invoke-Gate -ProjectPath $pre -Stage Export
    $preWarn = @($r.Warnings | Where-Object { $_ -match 'PRERELEASE' })
    if (-not $r.Error -and $r.Result.Ready -and $preWarn.Count -eq 1 -and $preWarn[0] -match [regex]::Escape('PSAppDeployToolkit 4.2.0-rc2') -and $r.Result.Warnings -contains $preWarn[0]) {
        Ok 'Export: Ready, exactly one prerelease warning naming 4.2.0-rc2 (also in Result.Warnings)'
    }
    else { Bad "Export prerelease -> error='$($r.Error)' warnings=$($r.Warnings -join ' | ')" }
    Initialize-TestDouble; Use-ProjectVersionResult -VersionText '4.2.0-rc2' -Prerelease 'rc2'
    $r = Invoke-Gate -ProjectPath $pre -Stage Finalize
    if (-not $r.Error -and @($r.Warnings | Where-Object { $_ -match 'PRERELEASE' }).Count -eq 0) { Ok 'Finalize: no prerelease warning (Export says it once)' }
    else { Bad "Finalize prerelease -> error='$($r.Error)' warnings=$($r.Warnings -join ' | ')" }
    Initialize-TestDouble; Use-ProjectVersionResult -VersionText '4.2.0' -Prerelease ''
    $r = Invoke-Gate -ProjectPath $pre -Stage Export
    if (-not $r.Error -and $r.Warnings.Count -eq 0) { Ok 'Export: a stable 4.2.0 gives no warning' }
    else { Bad "Export stable -> error='$($r.Error)' warnings=$($r.Warnings -join ' | ')" }

    # == [17] relative and PSDrive project paths ========================================================
    # .NET (ParseFile, the detectors' File reads) resolves a relative path against the PROCESS directory,
    # which Push-Location / Set-Location do not move. The gate must make the path absolute first, or
    # 'Export-Win32ToolkitIntuneWin -ProjectPath .\App' fails with a false parse error.
    Write-Host '[17] relative / PSDrive -ProjectPath is resolved against the PowerShell location' -ForegroundColor Cyan
    $goodScriptPath = Join-Path $good 'Invoke-AppDeployToolkit.ps1'
    Push-Location -LiteralPath $root
    try {
        if ([Environment]::CurrentDirectory.TrimEnd('\') -ne $root.TrimEnd('\')) { Ok 'precondition: the process directory is not the PowerShell location' }
        foreach ($stage in 'Finalize', 'Export') {
            Initialize-TestDouble
            $r = Invoke-Gate -ProjectPath '.\Good' -Stage $stage
            if (-not $r.Error -and $r.Result.Ready -and $r.Warnings.Count -eq 0) { Ok "'.\Good' / $stage -> Ready, 0 warnings" } else { Bad "'.\Good' / $stage -> $($r.Lines -join ' | ')" }
            if (@($script:shapeCalls)[-1] -ceq $goodScriptPath) { Ok "'.\Good' / $stage -> the detector gets the absolute script path" } else { Bad "'.\Good' / $stage -> detector path: $(@($script:shapeCalls)[-1])" }
        }

        Initialize-TestDouble
        $r = Invoke-Gate -ProjectPath '.\Missing' -Stage Finalize
        $missingAbs = Join-Path $root 'Missing'
        if ((Test-NotReady $r) -and @($r.Lines | Where-Object { $_ -match '^Invoke-AppDeployToolkit\.ps1 not found' -and $_.Contains("'$missingAbs'") }).Count -eq 1) { Ok "'.\Missing' -> 'not found' with the absolute path" }
        else { Bad "'.\Missing' -> $($r.Lines -join ' | ')" }

        Initialize-TestDouble
        Use-ShapeResult -Shape 'Unknown' -Dasv $null -Support 'Unsupported' -SupportReason 'Unknown template shape.'
        $r = Invoke-Gate -ProjectPath '.\Broken' -Stage Finalize
        $parseLine = @($r.Lines | Where-Object { $_ -match 'does not parse \(' })
        if ($parseLine.Count -eq 1 -and $parseLine[0] -notmatch 'could not be read' -and $parseLine[0].StartsWith((Join-Path $broken 'Invoke-AppDeployToolkit.ps1'))) { Ok "'.\Broken' -> the real parse error, reported on the absolute path" }
        else { Bad "'.\Broken' -> $($r.Lines -join ' | ')" }
    }
    finally { Pop-Location }

    $drive = 'W32TPR' + [guid]::NewGuid().ToString('N').Substring(0, 4)
    $null = New-PSDrive -Name $drive -PSProvider FileSystem -Root $root
    try {
        Initialize-TestDouble
        $r = Invoke-Gate -ProjectPath "${drive}:\Good" -Stage Export
        if (-not $r.Error -and $r.Result.Ready -and @($script:shapeCalls)[-1] -ceq $goodScriptPath) { Ok "'${drive}:\Good' (PSDrive) -> Ready, the detector gets the file-system path" }
        else { Bad "PSDrive -> $($r.Lines -join ' | ') detector: $(@($script:shapeCalls)[-1])" }
    }
    finally { Remove-PSDrive -Name $drive -ErrorAction SilentlyContinue }

    # A drive that does not exist (the drive above is gone now): still ONE W32T.PackageNotReady, never a
    # Join-Path 'Cannot find drive' error (this suite runs with ErrorActionPreference Stop).
    Initialize-TestDouble
    $r = Invoke-Gate -ProjectPath "${drive}:\Good" -Stage Finalize
    if ((Test-NotReady $r) -and @($r.Lines | Where-Object { $_ -match '^Invoke-AppDeployToolkit\.ps1 not found' }).Count -eq 1) { Ok 'unknown drive -> W32T.PackageNotReady "not found"' }
    else { Bad "unknown drive -> $($r.Error.FullyQualifiedErrorId): $($r.Error)" }

    Push-Location -LiteralPath $tier
    try {
        Initialize-TestDouble
        $x = Invoke-ExportGate -ProjectPath '.\ExpGood'
        if ($x.Error.FullyQualifiedErrorId -eq 'W32T.TestSentinel') { Ok "Export-Win32ToolkitIntuneWin -ProjectPath '.\ExpGood' -> past the gate (sentinel reached)" }
        else { Bad "Export '.\ExpGood' -> $($x.Error.FullyQualifiedErrorId): $($x.Error)" }
    }
    finally { Pop-Location }
}
finally {
    Remove-Item -LiteralPath $root -Recurse -Force -ErrorAction SilentlyContinue
}

