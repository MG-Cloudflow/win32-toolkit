<#
    Assert-Win32ToolkitPackageReady - the gate in front of Finalize and Export (D15, PKG-04, L5).

    THE BUG (PKG-04 / D15): Export packaged - and Publish uploaded - whatever Invoke-AppDeployToolkit.ps1
    happened to contain: a script win32-toolkit never patched (no AppConfig loader, so none of the
    configured install / uninstall / tattoo data reaches the device), a template layout this version
    cannot generate for, a script that does not parse under Windows PowerShell 5.1 (Intune's host), or a
    project without Invoke-AppDeployToolkit.exe (the launcher Intune now starts). All of them fail on
    every device, after the upload.

