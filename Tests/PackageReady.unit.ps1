# A spec 2.5 result. Defaults = a toolkit-generated (gen 2) PSADT 4.1 script with the tattoo.
function Use-ShapeResult {
    param(
        [string]$Shape = 'Psadt41', [AllowNull()][object]$Dasv = '4.1.8', [bool]$IsPatched = $true,
        [AllowNull()][object]$GeneratorVersion = 2, [bool]$HasTattoo = $true, [string]$Support = 'Supported',
        [string]$SupportReason = '', [string]$Reason = ''
    )
    $script:shape = [pscustomobject]@{
        Shape = $Shape; DeployAppScriptVersion = $Dasv; IsSupportedVersion = $true; IsPatched = $IsPatched
        GeneratorVersion = $GeneratorVersion; HasTattoo = $HasTattoo; ParseErrors = 0; MarkerIssues = [string[]]@()
        Support = $Support; SupportReason = $SupportReason; Reason = $Reason
    }
}
# A spec 2.4 result. Defaults = bundled 4.1.8 with a 4.1.8 script.
function Use-ProjectVersionResult {
    param([string]$VersionText = '4.1.8', [bool]$IsSupported = $true, [bool]$IsLegacy = $false, [string]$Reason = '', [string]$Warning = '', [string]$Prerelease = '')
    $script:pv = [pscustomobject]@{
        ModuleVersion = $null; Prerelease = $Prerelease; VersionText = $VersionText; DeployAppScriptVersion = '4.1.8'; Shape = 'Psadt41'
        Support = 'Supported'; IsSupported = $IsSupported; IsLegacy = $IsLegacy; Reason = $Reason; Warning = $Warning
    }
}
function Initialize-TestDouble {
    Use-ShapeResult; Use-ProjectVersionResult
    $script:ps51 = @(); $script:ps51Calls = 0; $script:shapeCalls = @()
}

# == Fixtures (temp copies only; nothing is executed) ===============================================
