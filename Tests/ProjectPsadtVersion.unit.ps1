<#
    Get-Win32ToolkitProjectPsadtVersion (ORG-14 / SCF-08 / GEN-11): which PSAppDeployToolkit a project
    bundles, and whether win32-toolkit supports that project.

    The helper reads the bundled module manifest (<Project>\PSAppDeployToolkit\PSAppDeployToolkit.psd1)
    and takes the deploy-script shape and its Support policy from Get-Win32ToolkitDeployScriptShape.
    That shape detector belongs to another work package, so it is ALWAYS shadowed here: the shadow
    returns the shape/version/support under test for each fake project, which keeps this suite
    independent of the detector's implementation.

    Asserts: Psadt41/4.1.8 and Psadt42ZeroConfig/4.2.0-rc2 are supported; a legacy (1.1.6-patched) 4.1
    project is supported AND flagged legacy with its warning; Psadt42Default, a 4.2 script with a 4.1.8
    bundled module, a missing bundled module, an out-of-range bundled module, an Unknown shape, a
    missing folder and a failing shape probe are not supported (and never throw); the result is
    derived on demand (no cache).

    Run:  pwsh -File Tests\ProjectPsadtVersion.unit.ps1
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent $PSScriptRoot
$fail = 0
function Ok($m)  { Write-Host "  PASS: $m" -ForegroundColor Green }
function Bad($m) { Write-Host "  FAIL: $m" -ForegroundColor Red; $script:fail++ }

$script:PsadtSupportedRange = [pscustomobject]@{ Min = [version]'4.1.0'; MaxExclusive = [version]'4.3.0'; Display = '4.1.x and 4.2.x' }
. (Join-Path $repo 'Private\Test-Win32ToolkitPsadtVersionSupported.ps1')
. (Join-Path $repo 'Private\Get-Win32ToolkitProjectPsadtVersion.ps1')

$legacyText = 'Invoke-AppDeployToolkit.ps1 was generated by an older win32-toolkit: its uninstall does not remove the legacy WOW6432Node tattoo; re-create the project with this version to get it.'

# -- shadow of the shape detector: keyed by project folder name ----------------------------------------
$script:shapeByProject = @{}
$script:shapeCalls = 0
function Get-Win32ToolkitDeployScriptShape {
    param([string]$Path)
    $script:shapeCalls++
    $key = Split-Path (Split-Path $Path -Parent) -Leaf
    $s = $script:shapeByProject[$key]
    if ($s -eq 'THROW') { throw 'shape probe exploded' }
    $s
}
function ShapeOf([string]$Shape, [string]$Version, [string]$Support, [string]$SupportReason = '') {
    [pscustomobject]@{
        Shape = $Shape; DeployAppScriptVersion = $Version; IsSupportedVersion = [bool]$Version; IsPatched = $true
        GeneratorVersion = 2; HasTattoo = $true; ParseErrors = 0; MarkerIssues = @(); Support = $Support
        SupportReason = $SupportReason; Reason = ''
    }
}

$work = Join-Path ([System.IO.Path]::GetTempPath()) ('w32ppv_' + [guid]::NewGuid().ToString('N').Substring(0, 6))
$null = New-Item -ItemType Directory -Path $work -Force

# Minimal fake project: a deploy script with DeployAppScriptVersion and (optionally) a bundled manifest.
function MakeProject([string]$Name, [string]$ScriptVersion, [string]$ModuleVersion, [string]$Prerelease = '') {
    $p = Join-Path $work $Name
    $null = New-Item -ItemType Directory -Path $p -Force
    Set-Content -LiteralPath (Join-Path $p 'Invoke-AppDeployToolkit.ps1') -Value ("`$adtSession = @{`r`n    DeployAppScriptVersion = '$ScriptVersion'`r`n}")
    if ($ModuleVersion) {
        $null = New-Item -ItemType Directory -Path (Join-Path $p 'PSAppDeployToolkit') -Force
        $psData = if ($Prerelease) { "@{ Prerelease = '$Prerelease' }" } else { '@{ Tags = @(''PSADT'') }' }
        Set-Content -LiteralPath (Join-Path $p 'PSAppDeployToolkit\PSAppDeployToolkit.psd1') -Value (@(
            '@{'
            "    ModuleVersion = '$ModuleVersion'"
            "    PrivateData   = @{ PSData = $psData }"
            '}') -join "`r`n")
    }
    $p
}

# ===================================================================================================
Write-Host "`n[1] supported projects" -ForegroundColor Cyan
$p = MakeProject 'p41' '4.1.8' '4.1.8'
$script:shapeByProject['p41'] = ShapeOf 'Psadt41' '4.1.8' 'Supported'
$v = Get-Win32ToolkitProjectPsadtVersion -ProjectPath $p
if ($v.IsSupported -and -not $v.IsLegacy -and $v.VersionText -eq '4.1.8' -and $v.ModuleVersion -eq [version]'4.1.8' -and $v.Prerelease -eq '' -and $v.Shape -eq 'Psadt41' -and $v.DeployAppScriptVersion -eq '4.1.8' -and $v.Support -eq 'Supported' -and $v.Reason -eq '' -and $v.Warning -eq '') {
    Ok 'Psadt41 / bundled 4.1.8 -> supported, VersionText 4.1.8, no reason, no warning'
} else { Bad "p41: $($v | ConvertTo-Json -Compress)" }

$p = MakeProject 'p42zc' '4.2.0' '4.2.0' 'rc2'
$script:shapeByProject['p42zc'] = ShapeOf 'Psadt42ZeroConfig' '4.2.0' 'Supported'
$v = Get-Win32ToolkitProjectPsadtVersion -ProjectPath $p
if ($v.IsSupported -and $v.VersionText -eq '4.2.0-rc2' -and $v.Prerelease -eq 'rc2' -and $v.ModuleVersion -eq [version]'4.2.0' -and $v.Shape -eq 'Psadt42ZeroConfig') {
    Ok 'Psadt42ZeroConfig / bundled 4.2.0-rc2 -> supported, VersionText carries the prerelease label'
} else { Bad "p42zc: $($v | ConvertTo-Json -Compress)" }

Write-Host "`n[2] legacy (deploy script patched by win32-toolkit 1.1.6 or older) - supported with a warning" -ForegroundColor Cyan
$p = MakeProject 'legacy' '4.1.8' '4.1.8'
$script:shapeByProject['legacy'] = ShapeOf 'Psadt41' '4.1.8' 'Legacy' $legacyText
$v = Get-Win32ToolkitProjectPsadtVersion -ProjectPath $p
if ($v.IsSupported -and $v.IsLegacy -and $v.Support -eq 'Legacy' -and $v.Reason -eq '' -and $v.Warning -match 'older win32-toolkit' -and $v.Warning -match 'WOW6432Node') {
    Ok "Support=Legacy / 4.1.8 -> IsSupported + IsLegacy + Warning: $($v.Warning)"
} else { Bad "legacy: $($v | ConvertTo-Json -Compress)" }
$p = MakeProject 'legacy2' '4.1.8' '4.1.8'
$script:shapeByProject['legacy2'] = ShapeOf 'Psadt41' '4.1.8' 'Legacy' ''
$v = Get-Win32ToolkitProjectPsadtVersion -ProjectPath $p
if ($v.IsLegacy -and $v.Warning -eq $legacyText) { Ok 'a Legacy shape without a SupportReason still yields the legacy warning text' } else { Bad "legacy2 warning: '$($v.Warning)'" }

Write-Host "`n[3] unsupported projects (never throw)" -ForegroundColor Cyan
$p = MakeProject 'p42def' '4.2.0' '4.2.0'
$script:shapeByProject['p42def'] = ShapeOf 'Psadt42Default' '4.2.0' 'Unsupported' 'Scaffolded from the PSADT 4.2 default template without Zero-Config.'
$v = Get-Win32ToolkitProjectPsadtVersion -ProjectPath $p
if (-not $v.IsSupported -and -not $v.IsLegacy -and $v.Shape -eq 'Psadt42Default' -and $v.Reason -match 'Psadt42Default' -and $v.VersionText -eq '4.2.0') { Ok "Psadt42Default -> not supported: $($v.Reason)" } else { Bad "p42def: $($v | ConvertTo-Json -Compress)" }

$p = MakeProject 'mismatch' '4.2.0' '4.1.8'
$script:shapeByProject['mismatch'] = ShapeOf 'Psadt42ZeroConfig' '4.2.0' 'Supported'
$v = Get-Win32ToolkitProjectPsadtVersion -ProjectPath $p
if (-not $v.IsSupported -and $v.Reason -match 'does not match' -and $v.Reason -match '4\.1\.8' -and $v.Reason -match '4\.2\.0') { Ok "4.2 script + bundled 4.1.8 -> not supported: $($v.Reason)" } else { Bad "mismatch: $($v | ConvertTo-Json -Compress)" }

$p = MakeProject 'nomodule' '4.1.8' ''
$script:shapeByProject['nomodule'] = ShapeOf 'Psadt41' '4.1.8' 'Supported'
$v = Get-Win32ToolkitProjectPsadtVersion -ProjectPath $p
if (-not $v.IsSupported -and $v.VersionText -eq 'unknown' -and $null -eq $v.ModuleVersion -and $v.Reason -match 'No bundled PSAppDeployToolkit') { Ok "missing bundled module -> not supported, VersionText 'unknown': $($v.Reason)" } else { Bad "nomodule: $($v | ConvertTo-Json -Compress)" }

$p = MakeProject 'p43' '4.3.0' '4.3.0'
$script:shapeByProject['p43'] = ShapeOf 'Psadt42ZeroConfig' '4.3.0' 'Supported'
$v = Get-Win32ToolkitProjectPsadtVersion -ProjectPath $p
if (-not $v.IsSupported -and $v.Reason -match 'outside the supported range' -and $v.Reason -match [regex]::Escape('4.1.x and 4.2.x')) { Ok "bundled 4.3.0 -> not supported even if the shape says Supported: $($v.Reason)" } else { Bad "p43: $($v | ConvertTo-Json -Compress)" }

$p = MakeProject 'unknown' '4.1.8' '4.1.8'
$script:shapeByProject['unknown'] = [pscustomobject]@{ Shape = 'Unknown'; DeployAppScriptVersion = $null; Support = 'Unsupported'; SupportReason = ''; Reason = 'no $adtSession hashtable' }
$v = Get-Win32ToolkitProjectPsadtVersion -ProjectPath $p
if (-not $v.IsSupported -and $v.Shape -eq 'Unknown' -and $v.Reason -match 'Unknown' -and $v.Reason -match 'adtSession') { Ok "Unknown shape -> not supported, detector reason carried: $($v.Reason)" } else { Bad "unknown: $($v | ConvertTo-Json -Compress)" }

$p = MakeProject 'boom' '4.1.8' '4.1.8'
$script:shapeByProject['boom'] = 'THROW'
$v = $null; $err = $null
try { $v = Get-Win32ToolkitProjectPsadtVersion -ProjectPath $p } catch { $err = $_ }
if (-not $err -and $v -and -not $v.IsSupported -and $v.Reason -match 'could not be determined') { Ok "a failing shape probe -> not supported, no throw: $($v.Reason)" } else { Bad "boom: $(if ($err) { "threw $($err.Exception.Message)" } else { $v | ConvertTo-Json -Compress })" }

$p = MakeProject 'badpsd1' '4.1.8' '4.1.8'
Set-Content -LiteralPath (Join-Path $p 'PSAppDeployToolkit\PSAppDeployToolkit.psd1') -Value '@{ ModuleVersion = '
$script:shapeByProject['badpsd1'] = ShapeOf 'Psadt41' '4.1.8' 'Supported'
$v = $null; $err = $null
try { $v = Get-Win32ToolkitProjectPsadtVersion -ProjectPath $p } catch { $err = $_ }
if (-not $err -and -not $v.IsSupported -and $v.VersionText -eq 'unknown' -and $v.Reason -match 'could not be read') { Ok "an unreadable bundled manifest -> not supported, no throw" } else { Bad "badpsd1: $(if ($err) { "threw $($err.Exception.Message)" } else { $v | ConvertTo-Json -Compress })" }

$before = $script:shapeCalls
$v = Get-Win32ToolkitProjectPsadtVersion -ProjectPath (Join-Path $work 'does-not-exist')
if (-not $v.IsSupported -and $v.Reason -match 'not found' -and $script:shapeCalls -eq $before) { Ok "missing project folder -> not supported, no shape probe: $($v.Reason)" } else { Bad "missing folder: $($v | ConvertTo-Json -Compress)" }

Write-Host "`n[4] derived on demand - never cached (GEN-11)" -ForegroundColor Cyan
$p = Join-Path $work 'p41'
$first = Get-Win32ToolkitProjectPsadtVersion -ProjectPath $p
Set-Content -LiteralPath (Join-Path $p 'PSAppDeployToolkit\PSAppDeployToolkit.psd1') -Value "@{ ModuleVersion = '4.2.0'; PrivateData = @{ PSData = @{ Prerelease = 'rc2' } } }"
$second = Get-Win32ToolkitProjectPsadtVersion -ProjectPath $p
if ($first.VersionText -eq '4.1.8' -and $first.IsSupported -and $second.VersionText -eq '4.2.0-rc2' -and -not $second.IsSupported) { Ok 'a swapped bundled module is seen on the next call (4.1.8 -> 4.2.0-rc2, now mismatched)' } else { Bad "first $($first.VersionText)/$($first.IsSupported), second $($second.VersionText)/$($second.IsSupported)" }

Remove-Item -LiteralPath $work -Recurse -Force -ErrorAction SilentlyContinue

Write-Host ''
if ($fail -eq 0) { Write-Host 'All ProjectPsadtVersion tests passed.' -ForegroundColor Green; exit 0 }
else { Write-Host "$fail ProjectPsadtVersion test(s) FAILED." -ForegroundColor Red; exit 1 }
