function Add-Win32ToolkitOrgHooks {
    <#
    .SYNOPSIS
        A1/A3 - place the org deploy-phase hook blocks, copy the hook files and the org PSADT extension
        module into a generated project.

    .DESCRIPTION
        Called from Apply-OrgTemplate on a deploy script generated by this win32-toolkit version. The
        anchors are toolkit-owned blocks, not PSADT's '## <Perform ... tasks here>' markers:

          * For each of the six phases (Pre-/Post-Install, Pre-/Post-Uninstall, Pre-/Post-Repair): when the
            template has hooks enabled AND Templates\<name>\Hooks\<Phase>.ps1 exists, the file is COPIED to
            SupportFiles\OrgHooks\ and a constant 'hook' block (Get-Win32ToolkitDeployScriptBlock -Name Hook)
            is placed with Set-Win32ToolkitPhaseBlock: LAST in a Pre-* phase, FIRST in a Post-* phase (before
            the install tattoo and the org completion prompt). The hook is DOT-SOURCED, so it runs in the
            phase's scope; it must fail with 'throw', never 'return', and never assign PSADT's read-only
            variable names. FailureAction 'Continue' wraps it in try/catch + Write-ADTLogEntry.
          * A phase without a hook file (or with hooks disabled) has its 'hook' block removed, so removing a
            hook file and re-applying cleanly removes the block.
          * A block anchor that cannot be found is FATAL (W32T.PhaseAnchorMissing propagates): a hook that
            silently does not run is worse than a failed build.

        Copy-not-splice: no operator text ever enters the deploy script.

        A3: every Templates\<name>\PSAppDeployToolkit.<Org>\ folder is copied to the project root, where
        the PSADT frontend imports it. Assert-Win32ToolkitOrgExtensionModule validates them FIRST (D11 /
        ORG-08: '<Dir>\<Dir>.psd1' with an existing RootModule; a RequiredModules entry naming
        PSAppDeployToolkit must be satisfied by the bundled PSADT - ModuleVersion minimum, RequiredVersion
        exact, MaximumVersion upper bound - because 4.1 and 4.2 projects coexist). A violation throws
        W32T.OrgExtensionInvalid with the fix before any block is placed, any file copied or the deploy
        script written. Apply-OrgTemplate runs the same check before its own first write.

        Order: validate, compute the hook blocks in memory, write the deploy script (UTF-8 BOM, host + 5.1
        parse; the original bytes are restored on W32T.GeneratedScriptInvalid), and only then copy the hook
        files and the extension module(s). Every hook / module script is parse-checked under real Windows
        PowerShell 5.1 (warn-only) because it runs on-device as 5.1.

    .PARAMETER ProjectPath
        The generated PSADT project.

    .PARAMETER Template
        The org-template object (schema 3.0+). Read defensively - Hooks/ExtensionModule may be absent on
        older templates.
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)][string]$ProjectPath,
        [Parameter(Mandatory)][PSCustomObject]$Template,
        # The run's base folder (its Templates\<name>\ holds hooks and the module); empty = the configured one.
        [string]$BasePath
    )

    $scriptPath = Join-Path $ProjectPath 'Invoke-AppDeployToolkit.ps1'
    if (-not (Test-Path -LiteralPath $scriptPath)) { return }

    # ── read feature flags defensively (no registry unless a feature is on) ──
    $hooksEnabled = $false; $failureAction = 'Fail'
    $hp = $Template.PSObject.Properties['Hooks']
    if ($hp -and $hp.Value) {
        if ($hp.Value.PSObject.Properties['Enabled']) { $hooksEnabled = [bool]$hp.Value.Enabled }
        if ($hooksEnabled -and $hp.Value.PSObject.Properties['FailureAction'] -and $hp.Value.FailureAction -in @('Fail', 'Continue')) {
            $failureAction = [string]$hp.Value.FailureAction
        }
    }
    # -- D11 / ORG-08: validate the extension module(s) BEFORE any block is placed, any file copied or the
    #    deploy script written (W32T.OrgExtensionInvalid). Nothing to validate when the feature is off.
    $modDirs = @(Assert-Win32ToolkitOrgExtensionModule -ProjectPath $ProjectPath -Template $Template -BasePath $BasePath)

    # -- resolve the template's asset folder only when hooks need it --
    $assetFolder = $null
    if ($hooksEnabled) {
        $tn = if ($Template.PSObject.Properties['TemplateName']) { [string]$Template.TemplateName } else { '' }
        if ($tn) {
            try { $assetFolder = Get-Win32ToolkitTemplateAssetFolder -TemplateName $tn -BasePath $BasePath } catch {
                Write-Verbose "Org hooks: could not resolve template asset folder - skipping ($($_.Exception.Message))"
            }
        }
    }

    # Phase -> fixed hook filename (compile-time constants).
    $phases = [ordered]@{
        'Pre-Install'    = 'PreInstall.ps1'
        'Post-Install'   = 'PostInstall.ps1'
        'Pre-Uninstall'  = 'PreUninstall.ps1'
        'Post-Uninstall' = 'PostUninstall.ps1'
        'Pre-Repair'     = 'PreRepair.ps1'
        'Post-Repair'    = 'PostRepair.ps1'
    }

    $originalBytes = [System.IO.File]::ReadAllBytes($scriptPath)
    $scr = [System.IO.File]::ReadAllText($scriptPath, [System.Text.Encoding]::UTF8)
    $original = $scr
    $hooksSrc = if ($assetFolder) { Join-Path $assetFolder 'Hooks' } else { $null }
    $destHookDir = Join-Path $ProjectPath 'SupportFiles\OrgHooks'
    $hookCopies = [System.Collections.Generic.List[object]]::new()

    # -- compute the hook blocks in memory (a missing anchor throws before anything is written) --
    foreach ($phase in $phases.Keys) {
        $file     = $phases[$phase]
        $srcFile  = if ($hooksSrc) { Join-Path $hooksSrc $file } else { $null }
        $wantHook = $hooksEnabled -and $srcFile -and (Test-Path -LiteralPath $srcFile)

        if ($wantHook) {
            # The copy below is byte-identical, so the source file is what runs on the device.
            $errs = @(Test-Win32ToolkitPS51Syntax -Path $srcFile)
            if ($errs.Count) {
                Write-Warning "Org hook '$file' has Windows PowerShell 5.1 syntax issue(s) - it runs on-device as 5.1: $($errs -join ' | ')"
            }
            $code = Get-Win32ToolkitDeployScriptBlock -Name Hook -Phase $phase -HookFile $file -FailureAction $failureAction
            $scr  = Set-Win32ToolkitPhaseBlock -Content $scr -Phase $phase -Slot 'hook' -Code $code
            $hookCopies.Add([pscustomobject]@{ Source = $srcFile; Destination = (Join-Path $destHookDir $file) })
        }
        else {
            # No hook for this phase -> no hook block (removes a stale one; a no-op otherwise).
            $scr = Remove-Win32ToolkitPhaseBlock -Content $scr -Phase $phase -Slot 'hook'
        }
    }

    if ($scr -cne $original) {
        # UTF-8 WITH BOM, host + 5.1 parse-checked; the original bytes are restored on failure.
        Write-Win32ToolkitDeployScript -Path $scriptPath -Content $scr -OriginalBytes $originalBytes
        Write-Verbose '  org hook blocks updated in Invoke-AppDeployToolkit.ps1'
    }

    # -- copies run last, after the deploy script was written --
    if ($hookCopies.Count -gt 0 -and -not (Test-Path -LiteralPath $destHookDir)) { New-Item -ItemType Directory -Path $destHookDir -Force | Out-Null }
    foreach ($hc in $hookCopies) { Copy-Item -LiteralPath $hc.Source -Destination $hc.Destination -Force }

    # -- A3: org PSADT extension module(s), validated above (Assert-Win32ToolkitOrgExtensionModule) --
    foreach ($md in $modDirs) {
        $dest = Join-Path $ProjectPath $md.Name
        if (Test-Path -LiteralPath $dest) { Remove-Item -LiteralPath $dest -Recurse -Force -ErrorAction SilentlyContinue }
        Copy-Item -LiteralPath $md.FullName -Destination $dest -Recurse -Force
        Get-ChildItem -LiteralPath $dest -Recurse -File -Include '*.ps1', '*.psm1' -ErrorAction SilentlyContinue | ForEach-Object {
            $e = @(Test-Win32ToolkitPS51Syntax -Path $_.FullName)
            if ($e.Count) { Write-Warning "Org extension module file '$($_.Name)' has 5.1 syntax issue(s): $($e -join ' | ')" }
        }
        Write-Verbose "  org extension module '$($md.Name)' copied into project root"
    }
}
