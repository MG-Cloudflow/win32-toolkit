function Get-Win32ToolkitProjectPsadtVersion {
    <#
    .SYNOPSIS
        Reports which PSAppDeployToolkit a project bundles and whether win32-toolkit supports it.
    .DESCRIPTION
        Derived ON DEMAND from the project folder and never cached (GEN-11): a stored value would go
        stale after a folder swap. Reads the bundled module manifest
        <ProjectPath>\PSAppDeployToolkit\PSAppDeployToolkit.psd1 (ModuleVersion + PrivateData.PSData.
        Prerelease) and the deploy-script shape from Get-Win32ToolkitDeployScriptShape (which owns the
        single shape/version/generator policy, the 'Support' value), so this helper and the packaging
        gate cannot drift apart.

        IsSupported = the shape's Support is 'Supported' or 'Legacy', AND the bundled ModuleVersion is in
        the supported range, AND it has the same Major.Minor as the script's DeployAppScriptVersion.
        A 'Legacy' project (deploy script patched by win32-toolkit 1.1.6 or older) is supported, with
        the Warning text set.

        Never throws for project content: a missing folder, a missing/unreadable manifest or a failing
        shape probe produce IsSupported = $false and a Reason.
    .PARAMETER ProjectPath
        The project folder (the one holding Invoke-AppDeployToolkit.ps1).
    .OUTPUTS
        [pscustomobject] with ModuleVersion, Prerelease, VersionText, DeployAppScriptVersion, Shape,
        Support, IsSupported, IsLegacy, Reason, Warning.
    #>
    [CmdletBinding()]
    [OutputType([pscustomobject])]
    param(
        [Parameter(Mandatory)]
        [ValidateNotNullOrEmpty()]
        [string]$ProjectPath
    )

    $legacyWarning = 'Invoke-AppDeployToolkit.ps1 was generated by an older win32-toolkit: its uninstall does not remove the legacy WOW6432Node tattoo; re-create the project with this version to get it.'

    $result = [pscustomobject]@{
        ModuleVersion          = $null
        Prerelease             = ''
        VersionText            = 'unknown'
        DeployAppScriptVersion = $null
        Shape                  = 'Unknown'
        Support                = 'Unsupported'
        IsSupported            = $false
        IsLegacy               = $false
        Reason                 = ''
        Warning                = ''
    }

    if (-not (Test-Path -LiteralPath $ProjectPath -PathType Container)) {
        $result.Reason = "Project folder not found: $ProjectPath"
        return $result
    }

    # -- Bundled module manifest ----------------------------------------------------------------------
    $reasons = [System.Collections.Generic.List[string]]::new()
    $manifest = Join-Path $ProjectPath 'PSAppDeployToolkit\PSAppDeployToolkit.psd1'
    if (Test-Path -LiteralPath $manifest -PathType Leaf) {
        try {
            $data = Import-PowerShellDataFile -LiteralPath $manifest -ErrorAction Stop
            $mv = $null
            if ([version]::TryParse([string]$data.ModuleVersion, [ref]$mv)) { $result.ModuleVersion = $mv }
            $pre = ''
            if ($data.PrivateData -and $data.PrivateData.PSData) { $pre = [string]$data.PrivateData.PSData.Prerelease }
            $result.Prerelease = $pre.Trim()
            if ($result.ModuleVersion) {
                $result.VersionText = if ($result.Prerelease) { "$($result.ModuleVersion)-$($result.Prerelease)" } else { "$($result.ModuleVersion)" }
            }
            else { $reasons.Add('The bundled PSAppDeployToolkit manifest has no valid ModuleVersion.') }
        }
        catch {
            $reasons.Add("The bundled PSAppDeployToolkit manifest could not be read: $($_.Exception.Message)")
        }
    }
    else {
        $reasons.Add('No bundled PSAppDeployToolkit module (PSAppDeployToolkit\PSAppDeployToolkit.psd1) in the project.')
    }

    # -- Deploy-script shape (policy lives in Get-Win32ToolkitDeployScriptShape) ----------------------
    $shape = $null
    try {
        $shape = Get-Win32ToolkitDeployScriptShape -Path (Join-Path $ProjectPath 'Invoke-AppDeployToolkit.ps1')
    }
    catch {
        $reasons.Add("The deploy script shape could not be determined: $($_.Exception.Message)")
        $shape = $null
    }
    if (-not $shape -and -not ($reasons -match 'shape could not be determined')) {
        $reasons.Add('The deploy script shape could not be determined.')
    }
    if ($shape) {
        $result.Shape                  = [string]$shape.Shape
        $result.DeployAppScriptVersion = $shape.DeployAppScriptVersion
        $result.Support                = [string]$shape.Support
        if ($result.Support -notin 'Supported', 'Legacy') {
            $why = @($shape.SupportReason, $shape.Reason) | Where-Object { $_ } | Select-Object -First 1
            if (-not $why) { $why = 'not a deploy-script layout this win32-toolkit version supports' }
            $reasons.Add("Deploy script shape $($result.Shape) is not supported: $(([string]$why).TrimEnd('.')).")
        }
    }

    # -- Bundled module vs. range and vs. the script's own version ------------------------------------
    if ($result.ModuleVersion) {
        if (-not (Test-Win32ToolkitPsadtVersionSupported -Version $result.ModuleVersion)) {
            $reasons.Add("Bundled PSAppDeployToolkit $($result.VersionText) is outside the supported range ($($script:PsadtSupportedRange.Display)).")
        }
        $sv = $null
        $svText = ([string]$result.DeployAppScriptVersion) -replace '[-+].*$', ''
        if (-not $result.DeployAppScriptVersion -or -not [version]::TryParse($svText, [ref]$sv)) {
            # Only worth saying when the shape itself was acceptable (otherwise its reason says enough).
            if ($result.Support -in 'Supported', 'Legacy') { $reasons.Add('The deploy script has no readable DeployAppScriptVersion.') }
        }
        elseif ($sv.Major -ne $result.ModuleVersion.Major -or $sv.Minor -ne $result.ModuleVersion.Minor) {
            $reasons.Add("Bundled PSAppDeployToolkit $($result.VersionText) does not match the deploy script's DeployAppScriptVersion $($result.DeployAppScriptVersion).")
        }
    }

    $result.IsSupported = ($reasons.Count -eq 0 -and $result.Support -in 'Supported', 'Legacy')
    $result.IsLegacy    = ($result.Support -eq 'Legacy')
    $result.Reason      = ($reasons -join ' ')
    if ($result.IsLegacy) {
        $result.Warning = if ($shape -and $shape.SupportReason) { [string]$shape.SupportReason } else { $legacyWarning }
    }
    return $result
}
