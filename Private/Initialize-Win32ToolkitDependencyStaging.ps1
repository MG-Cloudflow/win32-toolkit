function Initialize-Win32ToolkitDependencyStaging {
    <#
    .SYNOPSIS
        Stages the project's declared dependencies into Sandbox\Dependencies\ so the TEST/CAPTURE guest can
        install them BEFORE the app — mirroring what Intune does on a real device.
    .DESCRIPTION
        Intune app dependencies are a DEPLOYMENT-time relationship: the Intune Management Extension installs
        the dependency first on a managed device. The Sandbox / Hyper-V runs never touch Intune — they just
        execute PSADT — so without this the guest is a clean machine with the dependency MISSING. That is
        worst for the documentation capture: the app would install (or half-install) without its runtime and
        the detection rule / uninstall logic would be generated from a broken install.

        So each declared dependency is materialized into the project:
          winget:<id>              -> the installer is downloaded (latest) to Sandbox\Dependencies\<id>\
          project:<Template>\<Name>-> the packaged project is copied to Sandbox\Dependencies\<Name>\
          intune:<guid>            -> CANNOT be staged (we don't have the package) — warned and skipped

        Everything lands under Sandbox\, which Optimize-Win32ToolkitProject strips from the Staging copy, so
        none of it ever ships inside the .intunewin.

        It then writes:
          Sandbox\Dependencies\dependencies.json   the ordered install list (DATA)
          Sandbox\InstallDependencies.ps1          a VALUE-FREE 5.1-safe guest script that reads that JSON

        The generated script passes untrusted values (installer paths, winget silent args) to Start-Process
        as PARAMETERS read from JSON — they are never spliced into a code position. Same contract as
        designs/data-driven-generation.md. Each packaged ('project:') dependency runs in its OWN Windows
        PowerShell process (PSADT 4.2 refuses a second module copy per process), and the script exits with
        the first failing dependency's exact code (success = 0, 1707, 3010, 1641). Each dependency gets the
        guest runner's 25-minute limit (a hung installer is stopped and ends as 1460, Timeout), and each result
        is appended to Sandbox\Logs\PsadtExitCodes.log in the runner's format with the label 'dep:<name>'.
    .PARAMETER ProjectPath
        The project whose dependencies should be staged.
    .PARAMETER BasePath
        The base folder a 'project:' dependency is resolved against (<BasePath>\Projects\<Template>\<Name>).
        Empty: the configured base folder (Get-Win32ToolkitBasePath -NonInteractive, never a prompt); when none is
        configured, such a dependency cannot be resolved and is warned about.
    .OUTPUTS
        [int] the number of dependencies staged (0 when none are declared). A 'winget:' or 'project:' dependency
        that cannot be staged (download failed, project or base folder missing, copy failed) throws
        W32T.DependencyNotStaged and leaves nothing staged; an 'intune:' one is only warned about.
    #>
    [CmdletBinding()]
    [OutputType([int])]
    param(
        [Parameter(Mandatory)]
        [ValidateNotNullOrEmpty()]
        [string]$ProjectPath,

        [string]$BasePath
    )

    $deps = @(Get-Win32ToolkitDependencies -ProjectPath $ProjectPath)
    $depRoot    = Join-Path $ProjectPath 'Sandbox\Dependencies'
    $scriptPath = Join-Path $ProjectPath 'Sandbox\InstallDependencies.ps1'

    # ── the VALUE-FREE guest script (Windows PowerShell 5.1, UTF-8 WITH BOM) ───────────────────────
    # Defined BEFORE the reuse check: the staging may only be reused when its script is byte-identical
    # to what THIS generator writes (see property 4 below).
    $guest = @'
# Installs this project's declared dependencies BEFORE the app — the same thing Intune does on a real
# device (the Intune Management Extension installs a mobileAppDependency first). Generated by
# win32-toolkit: VALUE-FREE by design. Every untrusted value (installer path, winget silent args) is READ
# FROM JSON and passed to Start-Process as a PARAMETER — never spliced into a code position.
$ErrorActionPreference = 'Stop'
$manifest = 'C:\PSADT\Sandbox\Dependencies\dependencies.json'
if (-not (Test-Path -LiteralPath $manifest)) { Write-Host 'No dependencies to install.'; exit 0 }

$deps = Get-Content -LiteralPath $manifest -Raw -Encoding UTF8 | ConvertFrom-Json
# Success = 0 / 1707 (success), 3010 (soft reboot), 1641 (hard reboot) - the codes Intune treats as installed.
$okCodes = @(0, 1707, 3010, 1641)
# Each result is appended to the guest runner's exit-code log (Sandbox\Logs\PsadtExitCodes.log, the runner's line
# format with the label 'dep:<name>'), so the host prints it with the run's other codes and the run folder keeps it.
# A dependency gets the runner's 25-minute limit: a hung installer is stopped and ends as 1460 (Timeout).
$logDir = Join-Path $PSScriptRoot 'Logs'
$timeoutMs = 25 * 60000
foreach ($d in @($deps)) {
    Write-Host ("Installing dependency: " + $d.Name) -ForegroundColor Cyan
    $rc = 0
    $parent = 'direct'
    $p = $null
    if ($d.Type -eq 'psadt') {
        # ONE PSADT PACKAGE = ONE PROCESS: PSADT 4.2 refuses a second copy of its module in a process (even
        # the same version from another folder), and 4.1/4.2 cannot share one - so a packaged dependency
        # never runs inside this script's (or the next dependency's / the app's) process. The path is
        # quoted because Windows PowerShell 5.1 does not quote ArgumentList elements.
        $ps = Join-Path $env:WinDir 'System32\WindowsPowerShell\v1.0\powershell.exe'
        $p = Start-Process -FilePath $ps -ArgumentList @('-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', ('"' + $d.Path + '"'), '-DeploymentType', 'Install', '-DeployMode', 'Silent') -WorkingDirectory (Split-Path -Parent $d.Path) -PassThru
        $parent = 'x64-direct'
    }
    elseif ($d.Type -eq 'msix' -or $d.Type -eq 'appx') {
        # Start-Process on a msix opens the App Installer GUI and blocks forever. A failure is exit 1, never a throw.
        try { Add-AppxPackage -Path $d.Path -ErrorAction Stop; $rc = 0 }
        catch { Write-Host ("  " + $_.Exception.Message); $rc = 1 }
    }
    elseif ($d.SilentArgs) {
        $p = Start-Process -FilePath $d.Path -ArgumentList $d.SilentArgs -PassThru
    }
    else {
        $p = Start-Process -FilePath $d.Path -PassThru
    }
    if ($p) {
        $null = $p.Handle   # 5.1: cache the handle so ExitCode is available after WaitForExit
        if ($p.WaitForExit($timeoutMs)) { $rc = $p.ExitCode }
        else { & (Join-Path $env:WinDir 'System32\taskkill.exe') /PID $p.Id /T /F | Out-Null; $rc = 1460 }
        Write-Host ("  exit code: " + $rc)
    }
    $class = 'Failed'
    if ($rc -eq 0 -or $rc -eq 1707) { $class = 'Success' } elseif ($rc -eq 3010) { $class = 'SoftReboot' }
    elseif ($rc -eq 1641) { $class = 'HardReboot' } elseif ($rc -eq 1618) { $class = 'Retry' } elseif ($rc -eq 1460) { $class = 'Timeout' }
    try {
        if (-not (Test-Path -LiteralPath $logDir)) { New-Item -ItemType Directory -Path $logDir -Force | Out-Null }
        $label = 'dep:' + ([string]$d.Name -replace '[^A-Za-z0-9._+-]', '_')
        ('[{0}] {1} Install parent={2} exit={3} result={4}' -f ([DateTime]::UtcNow.ToString('yyyy-MM-dd HH:mm:ss', [Globalization.CultureInfo]::InvariantCulture) + 'Z'), $label, $parent, $rc, $class) |
            Add-Content -LiteralPath (Join-Path $logDir 'PsadtExitCodes.log') -Encoding UTF8
    }
    catch { Write-Host ("  could not record the exit code: " + $_.Exception.Message) }
    # PROPAGATE failure (Intune installs dependencies first and a failed dependency blocks the app).
    # Exiting non-zero here is what stops the Hyper-V dep phase from reporting success — and, with the
    # deps-checkpoint feature, from FREEZING a broken image that every later run of the project would
    # silently reuse. The exact code is the script's exit code (the capture records it).
    if ($okCodes -notcontains $rc) {
        Write-Host ("  FAILED: " + $d.Name + " (exit " + $rc + ")") -ForegroundColor Red
        exit $rc
    }
    Write-Host ("  installed: " + $d.Name) -ForegroundColor Green
}
Write-Host 'All dependencies installed.' -ForegroundColor Green
exit 0
'@
    # The exact bytes written (BOM + UTF-8 text) and their SHA256 - the generator's identity for reuse.
    $guestEncoding = New-Object System.Text.UTF8Encoding($true)
    $guestBytes    = [byte[]]($guestEncoding.GetPreamble() + $guestEncoding.GetBytes($guest))
    $guestSha      = $null
    try {
        $sha = [System.Security.Cryptography.SHA256]::Create()
        try { $guestSha = ([System.BitConverter]::ToString($sha.ComputeHash($guestBytes)) -replace '-', '') }
        finally { $sha.Dispose() }
    } catch { $guestSha = $null }

    # ── Staging reuse (hash-validated, HOST-side integrity marker) ────────────────────────────────
    # A full pipeline stages the SAME dependencies 2-3 times (capture + each test), wiping and
    # re-downloading identical binaries each time. Reuse the existing staging when: the cache is on,
    # the DECLARED set is unchanged, the staging is < 6 h old (deps are unpinned 'latest' — bound the
    # staleness), and the staged tree matches the marker EXACTLY. Four properties make this safe on
    # BOTH backends (under Sandbox the whole project — including this staging — was mounted READ-WRITE
    # into a guest that ran an untrusted installer):
    #   1. the marker lives OUTSIDE the project, under <BasePath>\Cache\winget\staging\ — the guest can
    #      tamper the staged files but can never forge the record they are checked against;
    #   2. EVERY recorded file (installers, dependencies.json, AND the generated
    #      Sandbox\InstallDependencies.ps1 the guest executes) must re-hash to its recorded SHA256;
    #   3. the on-disk file SET must equal the recorded set — a guest-ADDED file is a miss, not a ride-along;
    #   4. the staged Sandbox\InstallDependencies.ps1 must be byte-identical to the script THIS generator
    #      writes — after a toolkit upgrade that changed the template, a staging left by the old build
    #      (e.g. one that ran 'project:' dependencies in-process) is restaged, never reused.
    # Any mismatch or error restages from scratch (today's behavior).
    $declaredJson = ConvertTo-Json -InputObject @($deps | ForEach-Object { "$($_.Source):$($_.Ref)" }) -Compress
    $declaredHash = $null
    try {
        $sha = [System.Security.Cryptography.SHA256]::Create()
        try { $declaredHash = ([System.BitConverter]::ToString($sha.ComputeHash([System.Text.Encoding]::UTF8.GetBytes($declaredJson))) -replace '-', '') }
        finally { $sha.Dispose() }
    } catch { $declaredHash = $null }

    # Marker path: host-side cache root, keyed by the (case-normalized) project path.
    $stagedMark = $null
    try {
        $cacheRoot = Get-Win32ToolkitPipelineCacheRoot
        if ($cacheRoot -and $declaredHash) {
            $sha = [System.Security.Cryptography.SHA256]::Create()
            try {
                $projKey = ([System.BitConverter]::ToString($sha.ComputeHash([System.Text.Encoding]::UTF8.GetBytes($ProjectPath.ToLowerInvariant().TrimEnd('\')))) -replace '-', '').Substring(0, 16)
            } finally { $sha.Dispose() }
            $markDir = Join-Path $cacheRoot 'staging'
            if (-not (Test-Path -LiteralPath $markDir)) { New-Item -ItemType Directory -Path $markDir -Force | Out-Null }
            $stagedMark = Join-Path $markDir "$projKey.json"
        }
    } catch { $stagedMark = $null }

    # Enumerates the CURRENT staged tree as project-relative path -> SHA256 (covers the staged payloads,
    # dependencies.json, and the generated guest script — everything the guest run consumes).
    $enumerateStaged = {
        $list = @()
        if (Test-Path -LiteralPath $depRoot) {
            $list += @(Get-ChildItem -LiteralPath $depRoot -Recurse -File -ErrorAction SilentlyContinue)
        }
        if (Test-Path -LiteralPath $scriptPath) { $list += Get-Item -LiteralPath $scriptPath }
        @($list | Sort-Object FullName | ForEach-Object {
            @{ Path = $_.FullName.Substring($ProjectPath.Length + 1); Sha256 = (Get-FileHash -LiteralPath $_.FullName -Algorithm SHA256 -ErrorAction Stop).Hash }
        })
    }

    if ($deps.Count -gt 0 -and $stagedMark -and (Test-Path -LiteralPath $stagedMark)) {
        try {
            $mark = Get-Content -LiteralPath $stagedMark -Raw | ConvertFrom-Json
            # A marker an older build wrote after staging only SOME dependencies (it warned and went on) holds a
            # lower Count than the stageable set: never reuse that (S11-F4).
            $stageableCount = @($deps | Where-Object { $_.Source -ne 'intune' }).Count
            $fresh = $mark.DeclaredHash -eq $declaredHash -and [int]$mark.Count -eq $stageableCount -and
                     $mark.StagedAt -and (((Get-Date) - [datetime]$mark.StagedAt).TotalHours -lt 6)
            if ($fresh) {
                # Property 4: the staged guest script must be what THIS generator writes.
                $onDiskSha = if (Test-Path -LiteralPath $scriptPath) { (Get-FileHash -LiteralPath $scriptPath -Algorithm SHA256 -ErrorAction Stop).Hash } else { $null }
                if (-not $guestSha -or $onDiskSha -ne $guestSha) {
                    Write-Verbose 'The staged InstallDependencies.ps1 differs from the current generator template (restaging).'
                    $fresh = $false
                }
            }
            if ($fresh) {
                $current  = @(& $enumerateStaged)
                $expected = @($mark.Files)
                if ($current.Count -ne $expected.Count) { $fresh = $false }
                else {
                    for ($i = 0; $i -lt $current.Count; $i++) {
                        if ($current[$i].Path -ne $expected[$i].Path -or $current[$i].Sha256 -ne $expected[$i].Sha256) { $fresh = $false; break }
                    }
                }
            }
            if ($fresh) {
                Write-Host "✓ Dependencies already staged (hash-validated, $([int]$mark.Count) item(s)) — reusing." -ForegroundColor Green
                return [int]$mark.Count
            }
        }
        catch { Write-Verbose "Dependency staging reuse check failed (restaging): $($_.Exception.Message)" }
    }

    # Always start clean: a stale dependency from a previous run would silently install in the guest.
    if (Test-Path -LiteralPath $depRoot)    { Remove-Item -LiteralPath $depRoot -Recurse -Force -ErrorAction SilentlyContinue }
    if (Test-Path -LiteralPath $scriptPath) { Remove-Item -LiteralPath $scriptPath -Force -ErrorAction SilentlyContinue }
    if ($deps.Count -eq 0) { return 0 }

    New-Item -ItemType Directory -Path $depRoot -Force | Out-Null
    Write-Verbose "Staging $($deps.Count) dependency(ies) for the test/capture run..."

    # A 'winget:' or 'project:' dependency that cannot be staged FAILS CLOSED (test campaign 2026-10-21, S11-F4):
    # a run without a runtime the app declares would test - or worse, capture detection and uninstall data
    # from - a broken install. Nothing partial is left for the guest (no staging folder, no guest script, no
    # reuse marker), and the error names the dependency and the reason. 'intune:' stays a warning (TODO).
    # -ErrorAction Ignore: an absent file is the normal case here, and SilentlyContinue would still leave a
    # PathNotFound record in $Error / the caller's -ErrorVariable next to the one real error (re-verification
    # 2026-10-21, B3 #3).
    $notStaged = {
        param($Dependency, [string]$Why)
        Remove-Item -LiteralPath $depRoot -Recurse -Force -ErrorAction Ignore
        Remove-Item -LiteralPath $scriptPath -Force -ErrorAction Ignore
        if ($stagedMark) { Remove-Item -LiteralPath $stagedMark -Force -ErrorAction Ignore }
        $msg = "Dependency '$($Dependency.Source):$($Dependency.Ref)' could not be staged: $Why The test/capture run would not have it installed, so it is not started. Fix the dependency, or remove it (Set-Win32ToolkitAppDependency -ProjectPath '$ProjectPath' -Clear, then declare the others again), and re-run."
        throw [System.Management.Automation.ErrorRecord]::new([System.InvalidOperationException]::new($msg), 'W32T.DependencyNotStaged',
            [System.Management.Automation.ErrorCategory]::ObjectNotFound, "$($Dependency.Source):$($Dependency.Ref)")
    }

    $entries = [System.Collections.Generic.List[object]]::new()
    $usedLeaf = @{}   # staged 'project:' folder names (case-insensitive): two dependencies never share one

    foreach ($d in $deps) {
        switch ($d.Source) {

            'winget' {
                # Folder name must be filesystem-safe; the winget ID itself is preserved verbatim as DATA.
                $safe    = ($d.Ref -replace '[\\/:*?"<>|]', '_')
                $destDir = Join-Path $depRoot $safe
                New-Item -ItemType Directory -Path $destDir -Force | Out-Null
                try {
                    $dl = Download-OldVersionInstaller -AppId $d.Ref -ProjectPath $ProjectPath -DestinationDir $destDir
                    $entries.Add([pscustomobject]@{
                        Name       = $d.Ref
                        Type       = $dl.InstallerType                                          # exe|msi|msix|appx
                        Path       = "C:\PSADT\Sandbox\Dependencies\$safe\$($dl.InstallerName)" # guest path
                        SilentArgs = $dl.SilentArgs
                    })
                }
                catch {
                    if ($_.FullyQualifiedErrorId -like 'W32T.*') { & $notStaged $d "the winget download failed ($($_.FullyQualifiedErrorId): $($_.Exception.Message))." }
                    & $notStaged $d "the winget download failed ($($_.Exception.Message))."
                }
            }

            'project' {
                $leaf = Split-Path -Leaf $d.Ref
                # The caller's -BasePath wins over the registry value (test campaign 2026-10-21, S11-F3: a
                # 'Test-Win32ToolkitProject -BasePath B' run staged the dependency from the registry base A), and
                # the lookup never prompts: no base folder at all means the dependency cannot be resolved.
                $base = Get-Win32ToolkitBasePath -BasePath $BasePath -NonInteractive
                if ([string]::IsNullOrWhiteSpace($base)) {
                    & $notStaged $d 'no base folder is configured to resolve it against (pass -BasePath, or set the base folder).'
                }
                # Defence in depth (AppConfig.json can hold an old or hand-edited reference): only
                # '<Template>\<ProjectName>' that stays inside Projects\ is staged (S11-F5).
                $projectsFull = [System.IO.Path]::GetFullPath([string](Get-Win32ToolkitPaths -BasePath $base).Projects).TrimEnd('\')
                $refParts = @(([string]$d.Ref) -split '\\')
                $src = $null
                if ($refParts.Count -eq 2 -and -not [System.IO.Path]::IsPathRooted([string]$d.Ref)) {
                    $src = [System.IO.Path]::GetFullPath((Join-Path $projectsFull $d.Ref))
                }
                if (-not $src -or -not $src.StartsWith($projectsFull + '\', [System.StringComparison]::OrdinalIgnoreCase)) {
                    & $notStaged $d "its reference is not '<Template>\<ProjectName>' inside $projectsFull."
                }
                # A segment ending in '.' or ' ' is dropped by Windows ('T.\App' is 'T\App'), and an app never
                # depends on itself - compared as a normalized full path (the raw Projects\ copy or whichever path
                # the caller passes) and as its '<Template>\<ProjectName>' identity (re-verification 2026-10-21, B3 #2).
                if (@($refParts | Where-Object { $_ -match '[. ]$' }).Count -gt 0) {
                    & $notStaged $d "its reference is not '<Template>\<ProjectName>' inside $projectsFull (a name ends in '.' or ' ')."
                }
                $selfFull = [System.IO.Path]::GetFullPath($ProjectPath).TrimEnd('\')
                $selfId   = (Split-Path -Leaf (Split-Path -Parent $selfFull)) + '\' + (Split-Path -Leaf $selfFull)
                if ($src.TrimEnd('\').Equals($selfFull, [System.StringComparison]::OrdinalIgnoreCase) -or
                    ([string]$d.Ref).Equals($selfId, [System.StringComparison]::OrdinalIgnoreCase)) {
                    & $notStaged $d 'an app cannot depend on itself.'
                }
                if (-not (Test-Path -LiteralPath (Join-Path $src 'Invoke-AppDeployToolkit.ps1'))) {
                    & $notStaged $d "the project was not found (no Invoke-AppDeployToolkit.ps1 at $src)."
                }
                # Two dependencies with the same project name (Contoso\Tool, Other\Tool) must not share a folder.
                if ($usedLeaf.ContainsKey($leaf.ToLowerInvariant())) { $leaf = ($refParts -join '_') }
                $usedLeaf[$leaf.ToLowerInvariant()] = $true
                $destDir = Join-Path $depRoot $leaf
                New-Item -ItemType Directory -Path $destDir -Force | Out-Null
                # Copy CONTENTS so the PSADT script sits directly under the dependency folder. Its own
                # Sandbox\ artifacts are excluded — we only need it to be installable.
                try { Copy-Item -Path (Join-Path $src '*') -Destination $destDir -Recurse -Force -Exclude 'Sandbox' -ErrorAction Stop }
                catch {
                    if ($_.FullyQualifiedErrorId -like 'W32T.*') { throw }
                    & $notStaged $d "copying the project failed ($($_.Exception.Message))."
                }
                $entries.Add([pscustomobject]@{
                    Name       = $d.Ref
                    Type       = 'psadt'
                    Path       = "C:\PSADT\Sandbox\Dependencies\$leaf\Invoke-AppDeployToolkit.ps1"
                    SilentArgs = $null
                })
            }

            'intune' {
                Write-Warning "Dependency 'intune:$($d.Ref)' is an app id in the tenant — the toolkit has no package for it, so it CANNOT be installed in the test/capture guest. The Intune relationship will still be created at publish time. Declare it as 'winget:' or 'project:' if you need it present during testing."
            }
        }
    }

    if ($entries.Count -eq 0) {
        Remove-Item -LiteralPath $depRoot -Recurse -Force -ErrorAction Ignore
        return 0
    }

    # ── the DATA the guest script consumes ─────────────────────────────────────────────────────────
    $manifest = Join-Path $depRoot 'dependencies.json'
    $json     = ConvertTo-Json -InputObject @($entries) -Depth 5
    [System.IO.File]::WriteAllText($manifest, $json, (New-Object System.Text.UTF8Encoding($false)))

    # ── the guest script: written as the exact bytes hashed above (UTF-8 WITH BOM) ─────────────────
    [System.IO.File]::WriteAllBytes($scriptPath, $guestBytes)

    # Record what was staged (declared-set hash + per-file SHA256 over EVERYTHING the guest consumes,
    # incl. the generated script) in the HOST-side marker so the next call in this pipeline can REUSE it
    # instead of wiping + re-downloading. Best-effort: a failure just means the next call restages.
    if ($stagedMark) {
        try {
            $files = @(& $enumerateStaged)
            $markJson = ConvertTo-Json -InputObject @{ DeclaredHash = $declaredHash; StagedAt = (Get-Date).ToString('o'); Count = $entries.Count; Files = $files } -Depth 4
            [System.IO.File]::WriteAllText($stagedMark, $markJson, (New-Object System.Text.UTF8Encoding($false)))
        }
        catch { Write-Verbose "Could not record the staging marker (reuse disabled for the next call): $($_.Exception.Message)" }
    }

    Write-Host "✓ Dependencies staged: $(($entries | ForEach-Object { $_.Name }) -join ', ')" -ForegroundColor Green
    return $entries.Count
}
