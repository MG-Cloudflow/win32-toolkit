function Apply-OrgTemplate {
    <#
    .SYNOPSIS
        Applies an org template to a generated PSADT project: config, strings, dialog policy, assets, hooks.
    .DESCRIPTION
        Runs after Set-PSADTDataDrivenScript, on a deploy script generated by THIS win32-toolkit version
        (shape Supported, GeneratorVersion 2); anything else is refused with W32T.UnsupportedTemplateShape
        before a single file is written.

          * Config\config.psd1   - replaced by the sparse template config (New-Win32ToolkitSparseConfig).
          * Strings\strings.psd1 - balloon and progress texts; a missing anchor is fatal (W32T.OrgTemplateDrift).
          * Deploy script        - PSADT's default dialogs are removed from Pre-Install, Pre-Uninstall,
                                   Pre-Repair, Post-Install and Post-Repair and replaced by the constant
                                   'org-ui' blocks of the block catalog. No template value is spliced: the
                                   dialog policy is written as DATA to SupportFiles\AppConfig.json (OrgUi),
                                   together with App.ScriptAuthor.
          * Assets and org hooks / extension module (Add-Win32ToolkitTemplateAssets, Add-Win32ToolkitOrgHooks).

        What is guaranteed:
          * The inputs are all checked before anything is written: the template text (D9,
            W32T.OrgTemplateInvalid), the deploy-script shape (W32T.UnsupportedTemplateShape), the
            strings.psd1 anchors (W32T.OrgTemplateDrift), the org-ui block anchors, the extension
            module (Assert-Win32ToolkitOrgExtensionModule, W32T.OrgExtensionInvalid) and the computed
            config.psd1 / strings.psd1 text (one hashtable, no parse error; W32T.OrgTemplateInvalid).
          * The deploy script is written first; its writer (host + 5.1 parse) restores it and throws
            W32T.GeneratedScriptInvalid on failure, so config.psd1, strings.psd1 and AppConfig.json are then
            untouched too. They are written next.
          * The asset and hook copy runs last (Add-Win32ToolkitTemplateAssets, then Add-Win32ToolkitOrgHooks,
            which writes the hook blocks to the deploy script before it copies the hook files and the
            extension module).
        W32T.* errors propagate to the caller; any other failure is reported as a warning and returns $false.
    .PARAMETER ProjectPath
        The generated PSADT project.
    .PARAMETER Template
        The org-template object.
    .OUTPUTS
        [bool] $true when applied.
    #>
    [CmdletBinding()]
    param(
        [string]$ProjectPath,
        [PSCustomObject]$Template
    )

    try {
        # D9 defence in depth: text that PSADT 4.2 would expand never reaches config/strings/AppConfig.
        Assert-Win32ToolkitOrgTemplateText -Template $Template -Context 'apply'

        # Set-TextBlock (replace first regex match via index maths; -Required makes a miss fatal) lives in
        # Private\Set-Win32ToolkitTextBlock.ps1, dot-sourced by the loader.

        # Escape single quotes so a free-text template value (balloon/progress messages) stays a valid
        # single-quoted literal in the generated strings.psd1: EVERY PowerShell single-quote character is
        # doubled (ConvertTo-PSSingleQuoted: the apostrophe and the typographic U+2018/U+2019/U+201A/U+201B,
        # which also end a '...' literal under 5.1 and 7). [string]$null -> ''.
        function Esc { param([string]$s) ConvertTo-PSSingleQuoted $s }

        # Defensive template read: $Default for a missing (older-schema) property or a $null value.
        function Get-OrgUiField { param($Object, [string]$Name, $Default) if ($Object -and $Object.PSObject.Properties[$Name] -and $null -ne $Object.$Name) { $Object.$Name } else { $Default } }

        #── Deploy-script gate: BEFORE any write ───────────────────────────
        $scriptPath = Join-Path $ProjectPath 'Invoke-AppDeployToolkit.ps1'
        $shape = Get-Win32ToolkitDeployScriptShape -Path $scriptPath
        if ($shape.Support -ne 'Supported' -or $shape.GeneratorVersion -ne 2) {
            $gv = if ($null -eq $shape.GeneratorVersion) { 'none' } else { $shape.GeneratorVersion }
            $v  = if ($shape.DeployAppScriptVersion) { $shape.DeployAppScriptVersion } else { 'none' }
            $detail = if ($shape.Support -ne 'Supported' -and $shape.SupportReason) { " Detail: $($shape.SupportReason.TrimEnd('.'))." } else { '' }
            throw [System.Management.Automation.ErrorRecord]::new(
                [System.InvalidOperationException]::new("Unsupported PSADT template shape: $scriptPath; shape $($shape.Shape); DeployAppScriptVersion $v; supported: $($script:PsadtSupportedRange.Display). The deploy script was not generated by this win32-toolkit version (GeneratorVersion $gv): run the generator first; a project from an older win32-toolkit must be re-created.$detail Nothing was changed."),
                'W32T.UnsupportedTemplateShape', [System.Management.Automation.ErrorCategory]::InvalidData, $scriptPath)
        }

        #-- Extension-module gate (D11 / ORG-08): BEFORE any write --
        # Add-Win32ToolkitOrgHooks runs last and repeats the check; running it here keeps a broken extension
        # module (W32T.OrgExtensionInvalid) from leaving a half-applied project.
        $null = Assert-Win32ToolkitOrgExtensionModule -ProjectPath $ProjectPath -Template $Template

        #── config.psd1 (data-driven, F1) ──────────────────────────────────
        # REPLACE the scaffolded full config.psd1 with a SPARSE file carrying only the template's deltas.
        # PSADT superimposes it over its signed module default key-by-key.
        $configPath = Join-Path $ProjectPath 'Config\config.psd1'
        $cfgText = if (Test-Path $configPath) { New-Win32ToolkitSparseConfig -Template $Template } else { $null }

        #── strings.psd1 ───────────────────────────────────────────────────
        $strPath = Join-Path $ProjectPath 'Strings\strings.psd1'
        $str = $null
        if (Test-Path $strPath) {
            $str = Get-Content $strPath -Raw -Encoding UTF8

            # BalloonTip.Complete sub-block
            $newBalloon = "        # Text displayed in the balloon tip for successful completion of a deployment type.`r`n        Complete = @{`r`n            Install = '$(Esc $Template.BalloonComplete.Install)'`r`n            Repair = '$(Esc $Template.BalloonComplete.Repair)'`r`n            Uninstall = '$(Esc $Template.BalloonComplete.Uninstall)'`r`n        }"
            $str = Set-TextBlock -Text $str `
                -Pattern '(?s)        # Text displayed in the balloon tip for successful completion of a deployment type\.\r?\n        Complete = @\{[^}]*\}' `
                -Replacement $newBalloon -Multiline -Label 'balloon-complete messages' -Required

            # ProgressPrompt — entire block up to RestartPrompt
            $nl = if ($str -match '\r\n') { "`r`n" } else { "`n" }
            $newProg = "    ProgressPrompt = @{${nl}        # Default message displayed in the progress bar.${nl}        Message = @{${nl}            Install = '$(Esc $Template.ProgressMessage.Install)'${nl}            Repair = '$(Esc $Template.ProgressMessage.Repair)'${nl}            Uninstall = '$(Esc $Template.ProgressMessage.Uninstall)'${nl}        }${nl}${nl}        # Default message detail displayed in the progress bar.${nl}        MessageDetail = @{${nl}            Install = '$(Esc $Template.ProgressMessageDetail.Install)'${nl}            Repair = '$(Esc $Template.ProgressMessageDetail.Repair)'${nl}            Uninstall = '$(Esc $Template.ProgressMessageDetail.Uninstall)'${nl}        }${nl}${nl}        # The subtitle underneath the Install Title, e.g. Company Name. Only for Fluent dialogs.${nl}        Subtitle = @{${nl}            Install = '{Toolkit\CompanyName} - App Installation'${nl}            Repair = '{Toolkit\CompanyName} - App Repair'${nl}            Uninstall = '{Toolkit\CompanyName} - App Uninstallation'${nl}        }${nl}    }"
            $str = Set-TextBlock -Text $str `
                -Pattern '(?s)    ProgressPrompt = @\{.*?(?=\r?\n    RestartPrompt)' `
                -Replacement $newProg -Multiline -Label 'progress-prompt messages' -Required
        }

        #── Invoke-AppDeployToolkit.ps1: dialog policy as constant org-ui blocks ──
        # PSADT's default dialogs go; the toolkit block reads the policy from AppConfig.OrgUi at runtime.
        # Pre-Uninstall and Pre-Repair share the close-apps welcome (PSADT's own default does the same);
        # Post-Repair gets no completion prompt (4.1.8 parity).
        $scriptBytes = [System.IO.File]::ReadAllBytes($scriptPath)
        $scr = [System.IO.File]::ReadAllText($scriptPath, [System.Text.Encoding]::UTF8)
        $orgUiBlocks = [ordered]@{
            'Pre-Install'   = 'OrgUiPreInstall'
            'Pre-Uninstall' = 'OrgUiPreMaintenance'
            'Pre-Repair'    = 'OrgUiPreMaintenance'
            'Post-Install'  = 'OrgUiPostInstall'
            'Post-Repair'   = 'OrgUiPostRepair'
        }
        foreach ($phase in $orgUiBlocks.Keys) {
            $scr = Remove-Win32ToolkitPhaseDefaultUi -Content $scr -Phase $phase
            $scr = Set-Win32ToolkitPhaseBlock -Content $scr -Phase $phase -Slot 'org-ui' -Code (Get-Win32ToolkitDeployScriptBlock -Name $orgUiBlocks[$phase])
        }

        #── AppConfig.json: OrgUi policy + App.ScriptAuthor (DATA, read on the device) ──
        $wd = Get-OrgUiField $Template 'WelcomeDialog' $null
        $uw = Get-OrgUiField $Template 'UninstallWelcomeDialog' ([pscustomobject]@{ Enabled = $true; CloseProcessesCountdown = 60; PersistPrompt = $false; BlockExecution = $false })
        $pd = Get-OrgUiField $Template 'ProgressDialog' $null
        $cp = Get-OrgUiField $Template 'CompletionPrompt' $null
        $orgUi = [pscustomobject][ordered]@{
            SchemaVersion    = '1.0'
            Welcome          = [pscustomobject][ordered]@{
                Enabled                 = [bool](Get-OrgUiField $wd 'Enabled' $false)
                AllowDefer              = [bool](Get-OrgUiField $wd 'AllowDefer' $false)
                DeferTimes              = [int](Get-OrgUiField $wd 'DeferTimes' 0)
                CheckDiskSpace          = [bool](Get-OrgUiField $wd 'CheckDiskSpace' $false)
                PersistPrompt           = [bool](Get-OrgUiField $wd 'PersistPrompt' $false)
                BlockExecution          = [bool](Get-OrgUiField $wd 'BlockExecution' $false)
                CloseProcessesCountdown = [int](Get-OrgUiField $wd 'CloseProcessesCountdown' 0)
            }
            UninstallWelcome = [pscustomobject][ordered]@{
                Enabled                 = [bool](Get-OrgUiField $uw 'Enabled' $true)
                CloseProcessesCountdown = [int](Get-OrgUiField $uw 'CloseProcessesCountdown' 60)
                PersistPrompt           = [bool](Get-OrgUiField $uw 'PersistPrompt' $false)
                BlockExecution          = [bool](Get-OrgUiField $uw 'BlockExecution' $false)
            }
            Progress         = [pscustomobject][ordered]@{
                Enabled             = [bool](Get-OrgUiField $pd 'Enabled' $false)
                StatusMessage       = [string](Get-OrgUiField $pd 'StatusMessage' '')
                StatusMessageDetail = [string](Get-OrgUiField $pd 'StatusMessageDetail' '')
            }
            Completion       = [pscustomobject][ordered]@{
                Enabled         = [bool](Get-OrgUiField $cp 'Enabled' $false)
                Message         = [string](Get-OrgUiField $cp 'Message' '')
                ButtonRightText = [string](Get-OrgUiField $cp 'ButtonRightText' 'OK')
            }
        }
        $appCfg = Get-Win32ToolkitAppConfig -ProjectPath $ProjectPath
        if ($appCfg.PSObject.Properties['OrgUi']) { $appCfg.OrgUi = $orgUi }
        else { $appCfg | Add-Member -NotePropertyName OrgUi -NotePropertyValue $orgUi -Force }
        $author = [string](Get-OrgUiField $Template 'AppScriptAuthor' '')
        if ($appCfg.PSObject.Properties['App'] -and $appCfg.App) {
            if ($appCfg.App.PSObject.Properties['ScriptAuthor']) { $appCfg.App.ScriptAuthor = $author }
            else { $appCfg.App | Add-Member -NotePropertyName ScriptAuthor -NotePropertyValue $author -Force }
        }
        else { $appCfg | Add-Member -NotePropertyName App -NotePropertyValue ([pscustomobject]@{ ScriptAuthor = $author }) -Force }

        #-- psd1 gate: BEFORE any write (defence in depth) --
        # PSADT loads config.psd1 and strings.psd1 as data files on the device: text that does not parse to
        # ONE hashtable fails every deployment. Template text is escaped above; this refuses anything that
        # still slipped through (W32T.OrgTemplateInvalid), before a single file is written.
        foreach ($psd1 in @([pscustomobject]@{ Path = $configPath; Text = $cfgText }, [pscustomobject]@{ Path = $strPath; Text = $str })) {
            if ($null -eq $psd1.Text) { continue }
            $psd1Errors = $null
            $psd1Ast = [System.Management.Automation.Language.Parser]::ParseInput($psd1.Text, [ref]$null, [ref]$psd1Errors)
            $statements = @($psd1Ast.EndBlock.Statements)
            $isTable = $statements.Count -eq 1 -and $statements[0] -is [System.Management.Automation.Language.PipelineAst] -and
                @($statements[0].PipelineElements).Count -eq 1 -and
                $statements[0].PipelineElements[0] -is [System.Management.Automation.Language.CommandExpressionAst] -and
                $statements[0].PipelineElements[0].Expression -is [System.Management.Automation.Language.HashtableAst]
            if (@($psd1Errors).Count -gt 0 -or -not $isTable) {
                $why = if (@($psd1Errors).Count -gt 0) { "parse error: $($psd1Errors[0].Message.TrimEnd('.'))" } else { 'it is not a single hashtable' }
                throw [System.Management.Automation.ErrorRecord]::new(
                    [System.InvalidOperationException]::new("Org template '$($Template.TemplateName)' would make $($psd1.Path) invalid PowerShell data ($why), so every deployment would fail. Check the template's text fields. Nothing was changed."),
                    'W32T.OrgTemplateInvalid', [System.Management.Automation.ErrorCategory]::InvalidData, $psd1.Path)
            }
        }

        #── write (everything above succeeded) ─────────────────────────────
        # The deploy script goes FIRST: its writer is the only step that validates its output (host + 5.1
        # parse) and on failure restores the script and throws W32T.GeneratedScriptInvalid - before
        # config.psd1, strings.psd1 or AppConfig.json have been touched.
        Write-Win32ToolkitDeployScript -Path $scriptPath -Content $scr -OriginalBytes $scriptBytes
        # UTF-8 WITH BOM for the .psd1 files: read on-device by Windows PowerShell 5.1, which decodes a
        # BOM-less file as ANSI (non-ASCII CompanyName / dialog strings would mojibake).
        if ($null -ne $cfgText) {
            [System.IO.File]::WriteAllText($configPath, $cfgText, (New-Object System.Text.UTF8Encoding($true)))
            Write-Verbose '  config.psd1 replaced with sparse template config'
        }
        if ($null -ne $str) {
            [System.IO.File]::WriteAllText($strPath, $str, (New-Object System.Text.UTF8Encoding($true)))
            Write-Verbose '  strings.psd1 updated'
        }
        $null = Set-Win32ToolkitAppConfig -ProjectPath $ProjectPath -Config $appCfg
        Write-Verbose '  AppConfig.json: OrgUi + App.ScriptAuthor written'

        #── B1/B7: org branding assets (logo + Classic banner) ──────────────
        # Copies Templates\<name>\Assets\{AppIcon.png, Banner.Classic.png} into the project. The logo is a
        # precedence-respecting base (winget/manual/captured still win); opt-in via CustomAssets.
        $null = Add-Win32ToolkitTemplateAssets -ProjectPath $ProjectPath -Template $Template

        #── A1/A3: org hook scripts + extension module ──────────────────────
        # Copy-not-splice: operator scripts are copied into SupportFiles\OrgHooks\ (and any org PSADT
        # extension module into the project root); only constant 'hook' blocks are placed in the deploy
        # script. Opt-in per template (Hooks.Enabled / ExtensionModule).
        $null = Add-Win32ToolkitOrgHooks -ProjectPath $ProjectPath -Template $Template

        Write-Host "✓ Org template '$($Template.TemplateName)' applied to project" -ForegroundColor Green
        return $true
    }
    catch {
        # Fail-closed errors (template text, shape, drift, block anchors, extension module) are fatal.
        if ($_.FullyQualifiedErrorId -like 'W32T.*') { throw }
        Write-Warning "Failed to apply org template: $($_.Exception.Message)"
        return $false
    }
}
